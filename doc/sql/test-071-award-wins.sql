-- WHEN. After doc/sql/migration-071-award-wins.sql has been applied AND Process 44 has
-- run once at 1.1.54 or later (nightly main run, or tmdb-movie-preprocess-awards.sh).
-- Before the migration the file fails at the first statement that names a new column:
-- that is the expected answer, not a defect.
--
-- EXPECTED VALUES come from the preview of 2026-11-10
-- (check-071-award-wins-preview-20261110.txt, check-071-win-query-20261110.txt). The
-- base moves every night: the totals are orders of magnitude, the named cases are exact.
-- ============================================================================

SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;

SELECT '=== 1. the twelve columns of the migration ===' AS section;
SELECT COUNT(*) AS COLUMNS_PRESENT, 12 AS EXPECTED
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = DATABASE()
  AND ((TABLE_NAME IN ('T_WC_T2S_MOVIE_AWARD', 'T_WC_T2S_SERIE_AWARD', 'T_WC_T2S_PERSON_AWARD')
        AND COLUMN_NAME IN ('ID_STATEMENT', 'AWARD_YEAR', 'ID_CEREMONY_WIKIDATA', 'ID_MOVIE_FOR', 'ID_SERIE_FOR'))
    OR (TABLE_NAME = 'T_WC_T2S_AWARD' AND COLUMN_NAME = 'ID_AWARD_PARENT'));

SELECT '=== 2. rows per table. PRE_071_ROWS must be 0 (a row without statement is a row from before the build). Preview: about 14 351 movie rows, 156 300 person rows, 1 930 series rows ===' AS section;
SELECT 'T_WC_T2S_MOVIE_AWARD' AS LINK_TABLE, COUNT(*) AS LINK_ROWS, SUM(ID_STATEMENT IS NULL) AS PRE_071_ROWS,
       COUNT(DISTINCT ID_AWARD, ID_MOVIE) AS PAIRS, SUM(AWARD_YEAR IS NULL) AS ROWS_WITHOUT_YEAR, SUM(ID_CEREMONY_WIKIDATA IS NOT NULL) AS ROWS_WITH_CEREMONY
FROM T_WC_T2S_MOVIE_AWARD
UNION ALL
SELECT 'T_WC_T2S_SERIE_AWARD', COUNT(*), SUM(ID_STATEMENT IS NULL),
       COUNT(DISTINCT ID_AWARD, ID_SERIE), SUM(AWARD_YEAR IS NULL), SUM(ID_CEREMONY_WIKIDATA IS NOT NULL)
FROM T_WC_T2S_SERIE_AWARD
UNION ALL
SELECT 'T_WC_T2S_PERSON_AWARD', COUNT(*), SUM(ID_STATEMENT IS NULL),
       COUNT(DISTINCT ID_AWARD, ID_PERSON), SUM(AWARD_YEAR IS NULL), SUM(ID_CEREMONY_WIKIDATA IS NOT NULL)
FROM T_WC_T2S_PERSON_AWARD;

SELECT '=== 3. the logical key (ID_STATEMENT, entity, AWARD_YEAR) repeated: 0 on each line ===' AS section;
SELECT 'T_WC_T2S_MOVIE_AWARD' AS LINK_TABLE, COUNT(*) AS REPEATED_KEYS FROM (
  SELECT 1 AS x FROM T_WC_T2S_MOVIE_AWARD WHERE ID_STATEMENT IS NOT NULL
  GROUP BY ID_STATEMENT, ID_MOVIE, AWARD_YEAR HAVING COUNT(*) > 1) d
UNION ALL
SELECT 'T_WC_T2S_SERIE_AWARD', COUNT(*) FROM (
  SELECT 1 AS x FROM T_WC_T2S_SERIE_AWARD WHERE ID_STATEMENT IS NOT NULL
  GROUP BY ID_STATEMENT, ID_SERIE, AWARD_YEAR HAVING COUNT(*) > 1) d
UNION ALL
SELECT 'T_WC_T2S_PERSON_AWARD', COUNT(*) FROM (
  SELECT 1 AS x FROM T_WC_T2S_PERSON_AWARD WHERE ID_STATEMENT IS NOT NULL
  GROUP BY ID_STATEMENT, ID_PERSON, AWARD_YEAR HAVING COUNT(*) > 1) d;

SELECT '=== 4. years out of range (before 1000 or after next year): 0 on each line ===' AS section;
SELECT 'T_WC_T2S_MOVIE_AWARD' AS LINK_TABLE, SUM(AWARD_YEAR < 1000 OR AWARD_YEAR > YEAR(CURDATE()) + 1) AS YEARS_OUT_OF_RANGE, MIN(AWARD_YEAR) AS LOWEST_YEAR, MAX(AWARD_YEAR) AS HIGHEST_YEAR
FROM T_WC_T2S_MOVIE_AWARD WHERE AWARD_YEAR IS NOT NULL
UNION ALL
SELECT 'T_WC_T2S_SERIE_AWARD', SUM(AWARD_YEAR < 1000 OR AWARD_YEAR > YEAR(CURDATE()) + 1), MIN(AWARD_YEAR), MAX(AWARD_YEAR)
FROM T_WC_T2S_SERIE_AWARD WHERE AWARD_YEAR IS NOT NULL
UNION ALL
SELECT 'T_WC_T2S_PERSON_AWARD', SUM(AWARD_YEAR < 1000 OR AWARD_YEAR > YEAR(CURDATE()) + 1), MIN(AWARD_YEAR), MAX(AWARD_YEAR)
FROM T_WC_T2S_PERSON_AWARD WHERE AWARD_YEAR IS NOT NULL;

SELECT '=== 5. Katharine Hepburn (6598), Academy Award for Best Actress (269): four rows, 1934 Morning Glory (31777), 1968 Guess Who is Coming to Dinner (1879), 1969 The Lion in Winter (18988), 1982 On Golden Pond (11816) ===' AS section;
SELECT pa.ID_PERSON, pa.ID_AWARD, pa.AWARD_YEAR, pa.ID_MOVIE_FOR, m.MOVIE_TITLE, pa.ID_SERIE_FOR, pa.ID_CEREMONY_WIKIDATA, pa.DISPLAY_ORDER, pa.ID_STATEMENT
FROM T_WC_T2S_PERSON_AWARD pa
LEFT JOIN T_WC_T2S_MOVIE m ON m.ID_MOVIE = pa.ID_MOVIE_FOR
WHERE pa.ID_PERSON = 6598 AND pa.ID_AWARD = 269
ORDER BY pa.AWARD_YEAR;

SELECT '=== 6. Academy Award for Best Actress in 1982: one row, Katharine Hepburn (6598) ===' AS section;
SELECT pa.ID_PERSON, p.PERSON_NAME, pa.AWARD_YEAR, pa.ID_MOVIE_FOR
FROM T_WC_T2S_PERSON_AWARD pa
JOIN T_WC_T2S_AWARD a ON a.ID_AWARD = pa.ID_AWARD
JOIN T_WC_T2S_PERSON p ON p.ID_PERSON = pa.ID_PERSON
WHERE a.AWARD_NAME = 'Academy Award for Best Actress' AND pa.AWARD_YEAR = 1982;

SELECT '=== 7. Cesar Award for Best Film (25677) in 2010: one row, A Prophet (21575) ===' AS section;
SELECT ma.ID_MOVIE, m.MOVIE_TITLE, ma.AWARD_YEAR, ma.ID_CEREMONY_WIKIDATA
FROM T_WC_T2S_MOVIE_AWARD ma
JOIN T_WC_T2S_MOVIE m ON m.ID_MOVIE = ma.ID_MOVIE
WHERE ma.ID_AWARD = 25677 AND ma.AWARD_YEAR = 2010;

SELECT '=== 8. the counts on T_WC_T2S_AWARD are distinct winners: awards where a count differs, 0 on each line ===' AS section;
SELECT 'MOVIE_COUNT' AS COUNT_COLUMN, COUNT(*) AS AWARDS_THAT_DIFFER
FROM T_WC_T2S_AWARD a
LEFT JOIN (SELECT ID_AWARD, COUNT(DISTINCT ID_MOVIE) AS N FROM T_WC_T2S_MOVIE_AWARD GROUP BY ID_AWARD) x ON x.ID_AWARD = a.ID_AWARD
WHERE COALESCE(a.MOVIE_COUNT, 0) <> COALESCE(x.N, 0)
UNION ALL
SELECT 'SERIE_COUNT', COUNT(*)
FROM T_WC_T2S_AWARD a
LEFT JOIN (SELECT ID_AWARD, COUNT(DISTINCT ID_SERIE) AS N FROM T_WC_T2S_SERIE_AWARD GROUP BY ID_AWARD) x ON x.ID_AWARD = a.ID_AWARD
WHERE COALESCE(a.SERIE_COUNT, 0) <> COALESCE(x.N, 0)
UNION ALL
SELECT 'PERSON_COUNT', COUNT(*)
FROM T_WC_T2S_AWARD a
LEFT JOIN (SELECT ID_AWARD, COUNT(DISTINCT ID_PERSON) AS N FROM T_WC_T2S_PERSON_AWARD GROUP BY ID_AWARD) x ON x.ID_AWARD = a.ID_AWARD
WHERE COALESCE(a.PERSON_COUNT, 0) <> COALESCE(x.N, 0);

SELECT '=== 9. DISPLAY_ORDER is the same on every row of an entity within an award: 0 on each line ===' AS section;
SELECT 'T_WC_T2S_MOVIE_AWARD' AS LINK_TABLE, COUNT(*) AS PAIRS_WITH_SEVERAL_ORDERS FROM (
  SELECT 1 AS x FROM T_WC_T2S_MOVIE_AWARD GROUP BY ID_AWARD, ID_MOVIE HAVING COUNT(DISTINCT DISPLAY_ORDER) > 1) d
UNION ALL
SELECT 'T_WC_T2S_SERIE_AWARD', COUNT(*) FROM (
  SELECT 1 AS x FROM T_WC_T2S_SERIE_AWARD GROUP BY ID_AWARD, ID_SERIE HAVING COUNT(DISTINCT DISPLAY_ORDER) > 1) d
UNION ALL
SELECT 'T_WC_T2S_PERSON_AWARD', COUNT(*) FROM (
  SELECT 1 AS x FROM T_WC_T2S_PERSON_AWARD GROUP BY ID_AWARD, ID_PERSON HAVING COUNT(DISTINCT DISPLAY_ORDER) > 1) d;

SELECT '=== 10. the work rewarded, on persons. Preview: about 14 900 rows with a movie, 2 900 with a series ===' AS section;
SELECT COUNT(*) AS PERSON_ROWS, SUM(ID_MOVIE_FOR IS NOT NULL) AS WITH_MOVIE, SUM(ID_SERIE_FOR IS NOT NULL) AS WITH_SERIE,
       SUM(ID_MOVIE_FOR IS NOT NULL AND ID_SERIE_FOR IS NOT NULL) AS WITH_BOTH
FROM T_WC_T2S_PERSON_AWARD;

SELECT '=== 11. a work that is no longer a T2S movie or series: 0 on each line ===' AS section;
SELECT 'ID_MOVIE_FOR' AS WORK_COLUMN, COUNT(*) AS DANGLING
FROM T_WC_T2S_PERSON_AWARD pa LEFT JOIN T_WC_T2S_MOVIE m ON m.ID_MOVIE = pa.ID_MOVIE_FOR
WHERE pa.ID_MOVIE_FOR IS NOT NULL AND m.ID_MOVIE IS NULL
UNION ALL
SELECT 'ID_SERIE_FOR', COUNT(*)
FROM T_WC_T2S_PERSON_AWARD pa LEFT JOIN T_WC_T2S_SERIE s ON s.ID_SERIE = pa.ID_SERIE_FOR
WHERE pa.ID_SERIE_FOR IS NOT NULL AND s.ID_SERIE IS NULL;

SELECT '=== 12. persons with the most wins of one award (several rows for one pair is the point of -071) ===' AS section;
SELECT pa.ID_PERSON, p.PERSON_NAME, a.AWARD_NAME, COUNT(*) AS WINS, MIN(pa.AWARD_YEAR) AS FIRST_YEAR, MAX(pa.AWARD_YEAR) AS LAST_YEAR
FROM T_WC_T2S_PERSON_AWARD pa
JOIN T_WC_T2S_AWARD a ON a.ID_AWARD = pa.ID_AWARD
JOIN T_WC_T2S_PERSON p ON p.ID_PERSON = pa.ID_PERSON
GROUP BY pa.ID_PERSON, pa.ID_AWARD
ORDER BY WINS DESC, pa.ID_PERSON
LIMIT 15;

SELECT '=== 13. families. Before the crawler load of WIKIDATA-CRAWLER-032: about 1 485 categories with a parent, 194 families, 53 under the Academy Awards (10464). After it: about 4 455 categories ===' AS section;
SELECT COUNT(*) AS AWARD_ROWS, SUM(ID_AWARD_PARENT IS NOT NULL) AS WITH_PARENT, COUNT(DISTINCT ID_AWARD_PARENT) AS FAMILIES,
       SUM(ID_AWARD_PARENT = 10464) AS UNDER_ACADEMY_AWARDS, SUM(ID_AWARD_PARENT = ID_AWARD) AS OWN_PARENT_MUST_BE_0
FROM T_WC_T2S_AWARD;

SELECT '=== 14. a parent that is not an award row: 0. CATEGORIES_UNDER_A_NESTED_FAMILY is a fact, not a fault: ID_AWARD_PARENT is the direct family, and a family may belong to a larger one ===' AS section;
SELECT SUM(f.ID_AWARD IS NULL) AS PARENT_MISSING, SUM(f.ID_AWARD_PARENT IS NOT NULL) AS CATEGORIES_UNDER_A_NESTED_FAMILY
FROM T_WC_T2S_AWARD c
LEFT JOIN T_WC_T2S_AWARD f ON f.ID_AWARD = c.ID_AWARD_PARENT
WHERE c.ID_AWARD_PARENT IS NOT NULL;

SELECT '=== 14b. the nested families: a family that has a family itself, with its number of categories (a question on the larger family needs both levels) ===' AS section;
SELECT f.ID_AWARD, f.AWARD_NAME, f.ID_AWARD_PARENT, g.AWARD_NAME AS LARGER_FAMILY, g.ID_AWARD_PARENT AS THIRD_LEVEL_MUST_BE_NULL,
       (SELECT COUNT(*) FROM T_WC_T2S_AWARD c WHERE c.ID_AWARD_PARENT = f.ID_AWARD) AS CATEGORIES
FROM T_WC_T2S_AWARD f
JOIN T_WC_T2S_AWARD g ON g.ID_AWARD = f.ID_AWARD_PARENT
WHERE EXISTS (SELECT 1 FROM T_WC_T2S_AWARD c WHERE c.ID_AWARD_PARENT = f.ID_AWARD)
ORDER BY CATEGORIES DESC, f.ID_AWARD
LIMIT 30;

SELECT '=== 15. the family of four categories: Best Actress (269) has the Academy Awards today; Best Picture (146) only after the crawler load ===' AS section;
SELECT c.ID_AWARD, c.AWARD_NAME, c.ID_AWARD_PARENT, f.AWARD_NAME AS FAMILY_NAME
FROM T_WC_T2S_AWARD c
LEFT JOIN T_WC_T2S_AWARD f ON f.ID_AWARD = c.ID_AWARD_PARENT
WHERE c.ID_AWARD IN (269, 146, 25677, 13720)
ORDER BY c.ID_AWARD;

SELECT '=== 16. family acceptance (2313, 2349): the Academy Awards of Katharine Hepburn (6598), 4 expected today, and of Walt Disney by name, more than 10 once the crawler has loaded P361 and P527 ===' AS section;
SELECT p.ID_PERSON, p.PERSON_NAME, COUNT(*) AS ACADEMY_AWARD_WINS, COUNT(DISTINCT pa.ID_AWARD) AS CATEGORIES
FROM T_WC_T2S_PERSON_AWARD pa
JOIN T_WC_T2S_AWARD c ON c.ID_AWARD = pa.ID_AWARD
JOIN T_WC_T2S_PERSON p ON p.ID_PERSON = pa.ID_PERSON
WHERE (c.ID_AWARD_PARENT = 10464 OR c.ID_AWARD = 10464)
  AND (p.ID_PERSON = 6598 OR p.PERSON_NAME = 'Walt Disney')
GROUP BY p.ID_PERSON, p.PERSON_NAME;
