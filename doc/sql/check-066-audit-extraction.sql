-- Deux jeux de resultats normalises, relies par ID_STATEMENT.
-- Le second inventorie tous les parents; les valeurs item/time/quantity sont developpees.
-- Pour string/media/external_id, consulter leur table typee: aucune conversion implicite.

WITH works AS (
 SELECT 'movie' AS ITEM_TYPE, ID_MOVIE AS ID_ITEM, ID_WIKIDATA FROM T_WC_T2S_MOVIE WHERE COALESCE(DELETED,0)=0
 UNION ALL
 SELECT 'serie', ID_SERIE, ID_WIKIDATA FROM T_WC_T2S_SERIE WHERE COALESCE(DELETED,0)=0
), scope AS (
 SELECT s.* FROM T_WC_WIKIDATA_STATEMENT s
 WHERE s.ID_PROPERTY IN ('P2130','P2142')
 AND EXISTS (SELECT 1 FROM works w WHERE w.ID_WIKIDATA=s.ID_WIKIDATA)
), eligible AS (
 SELECT s.* FROM scope s WHERE COALESCE(s.DELETED,0)=0
 AND (s.`RANK` IS NULL OR s.`RANK`<>'deprecated') AND s.VALUE_TYPE='quantity'
)
SELECT s.ID_STATEMENT,s.STATEMENT_GUID,w.ITEM_TYPE,w.ID_ITEM,s.ID_WIKIDATA,s.ID_PROPERTY,
 CASE s.ID_PROPERTY WHEN 'P2130' THEN 'budget' WHEN 'P2142' THEN 'box_office' END AS FINANCE_KIND,
 q.AMOUNT,q.UNIT_ID_WIKIDATA AS ID_CURRENCY,CASE q.UNIT_ID_WIKIDATA WHEN 'Q4917' THEN 'USD' WHEN 'Q4916' THEN 'EUR' WHEN 'Q25224' THEN 'GBP' WHEN 'Q8146' THEN 'JPY' WHEN 'Q41044' THEN 'RUB' WHEN 'Q1104069' THEN 'CAD' WHEN 'Q259502' THEN 'AUD' WHEN 'Q39099' THEN 'CNY' END AS CURRENCY_CODE,
 q.LOWER_BOUND,q.UPPER_BOUND,s.`RANK` AS WIKIDATA_RANK,s.IS_VALID,s.DISPLAY_ORDER
FROM eligible s JOIN T_WC_WIKIDATA_QUANTITY_VALUE q ON q.ID_STATEMENT=s.ID_STATEMENT
JOIN works w ON w.ID_WIKIDATA=s.ID_WIKIDATA
WHERE q.AMOUNT IS NOT NULL
ORDER BY w.ITEM_TYPE,w.ID_ITEM,s.ID_STATEMENT;

WITH works AS (
 SELECT 'movie' AS ITEM_TYPE, ID_MOVIE AS ID_ITEM, ID_WIKIDATA FROM T_WC_T2S_MOVIE WHERE COALESCE(DELETED,0)=0
 UNION ALL
 SELECT 'serie', ID_SERIE, ID_WIKIDATA FROM T_WC_T2S_SERIE WHERE COALESCE(DELETED,0)=0
), scope AS (
 SELECT s.* FROM T_WC_WIKIDATA_STATEMENT s
 WHERE s.ID_PROPERTY IN ('P2130','P2142')
 AND EXISTS (SELECT 1 FROM works w WHERE w.ID_WIKIDATA=s.ID_WIKIDATA)
), eligible AS (
 SELECT s.* FROM scope s WHERE COALESCE(s.DELETED,0)=0
 AND (s.`RANK` IS NULL OR s.`RANK`<>'deprecated') AND s.VALUE_TYPE='quantity'
)
SELECT sq.ID_STATEMENT,sq.ID_STATEMENT_QUALIFIER,sq.ID_QUALIFIER_PROPERTY,
 sq.VALUE_TYPE,sq.DISPLAY_ORDER,sq.IS_VALID,iv.ID_ITEM,
 tv.RAW_TIME_VALUE,tv.TIME_PRECISION,tv.CALENDAR_MODEL,tv.TIMEZONE_OFFSET,
 tv.YEAR_VALUE,tv.MONTH_VALUE,tv.DAY_VALUE,tv.DATE_START,tv.DATE_END,
 qv.AMOUNT,qv.UNIT_ID_WIKIDATA,qv.LOWER_BOUND,qv.UPPER_BOUND
FROM eligible s JOIN T_WC_WIKIDATA_STATEMENT_QUALIFIER sq ON sq.ID_STATEMENT=s.ID_STATEMENT
LEFT JOIN T_WC_WIKIDATA_QUALIFIER_ITEM_VALUE iv ON iv.ID_STATEMENT_QUALIFIER=sq.ID_STATEMENT_QUALIFIER AND sq.VALUE_TYPE='item'
LEFT JOIN T_WC_WIKIDATA_QUALIFIER_TIME_VALUE tv ON tv.ID_STATEMENT_QUALIFIER=sq.ID_STATEMENT_QUALIFIER AND sq.VALUE_TYPE='time'
LEFT JOIN T_WC_WIKIDATA_QUALIFIER_QUANTITY_VALUE qv ON qv.ID_STATEMENT_QUALIFIER=sq.ID_STATEMENT_QUALIFIER AND sq.VALUE_TYPE='quantity'
WHERE COALESCE(sq.DELETED,0)=0
AND EXISTS (SELECT 1 FROM T_WC_WIKIDATA_QUANTITY_VALUE q WHERE q.ID_STATEMENT=s.ID_STATEMENT AND q.AMOUNT IS NOT NULL)
ORDER BY sq.ID_STATEMENT,sq.ID_QUALIFIER_PROPERTY,sq.DISPLAY_ORDER,sq.ID_STATEMENT_QUALIFIER;
