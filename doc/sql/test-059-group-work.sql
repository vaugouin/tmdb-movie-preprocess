SELECT 'G. Dry run: what the member rule WOULD attach per GROUP_SOURCE, P108 and P54 included' AS SECTION;

-- Members only (MEMBER_COUNT >= 2 AND MEMBER_SHARE >= 0.4), computed from the credit
-- tables and not from the stored rows, so P108 and P54 appear. The group-credit half
-- of the rule is left out: it does not depend on the family. This is the measure the
-- ticket asked for before deciding the exclusion.
SELECT 'movie' AS MAJOR, x.GROUP_SOURCE, COUNT(*) AS WOULD_ATTACH,
       COUNT(DISTINCT x.ID_GROUP) AS GROUPS_WITH_WORKS,
       (SELECT COUNT(*) FROM `T_WC_T2S_GROUP` g2 WHERE g2.GROUP_SOURCE = x.GROUP_SOURCE) AS GROUPS_IN_FAMILY,
       MAX(x.MEMBERS) AS MAX_MEMBERS_ON_ONE_WORK
FROM (
    SELECT g.GROUP_SOURCE, pg.ID_GROUP, pm.ID_MOVIE, COUNT(DISTINCT pm.ID_PERSON) AS MEMBERS
    FROM `T_WC_T2S_GROUP` g
    INNER JOIN T_WC_T2S_PERSON_GROUP pg ON pg.ID_GROUP = g.ID_GROUP AND COALESCE(pg.DELETED, 0) = 0
    INNER JOIN T_WC_T2S_PERSON_MOVIE pm ON pm.ID_PERSON = pg.ID_PERSON AND COALESCE(pm.DELETED, 0) = 0
    WHERE g.PERSON_COUNT >= 2
    GROUP BY g.GROUP_SOURCE, pg.ID_GROUP, pm.ID_MOVIE, g.PERSON_COUNT
    HAVING COUNT(DISTINCT pm.ID_PERSON) >= 2
       AND COUNT(DISTINCT pm.ID_PERSON) / g.PERSON_COUNT >= 0.4
) x
GROUP BY x.GROUP_SOURCE
ORDER BY x.GROUP_SOURCE;

SELECT 'serie' AS MAJOR, x.GROUP_SOURCE, COUNT(*) AS WOULD_ATTACH,
       COUNT(DISTINCT x.ID_GROUP) AS GROUPS_WITH_WORKS,
       (SELECT COUNT(*) FROM `T_WC_T2S_GROUP` g2 WHERE g2.GROUP_SOURCE = x.GROUP_SOURCE) AS GROUPS_IN_FAMILY,
       MAX(x.MEMBERS) AS MAX_MEMBERS_ON_ONE_WORK
FROM (
    SELECT g.GROUP_SOURCE, c.ID_GROUP, c.ID_SERIE, COUNT(DISTINCT c.ID_PERSON) AS MEMBERS
    FROM (
        SELECT pg.ID_GROUP, ps.ID_SERIE, ps.ID_PERSON
        FROM T_WC_T2S_PERSON_GROUP pg
        INNER JOIN T_WC_T2S_PERSON_SERIE ps ON ps.ID_PERSON = pg.ID_PERSON AND COALESCE(ps.DELETED, 0) = 0
        WHERE COALESCE(pg.DELETED, 0) = 0
        UNION
        SELECT pg.ID_GROUP, pa.ID_SERIE, pa.ID_PERSON
        FROM T_WC_T2S_PERSON_GROUP pg
        INNER JOIN T_WC_T2S_PERSON_SEASON pa ON pa.ID_PERSON = pg.ID_PERSON AND COALESCE(pa.DELETED, 0) = 0
        WHERE COALESCE(pg.DELETED, 0) = 0
        UNION
        SELECT pg.ID_GROUP, pe.ID_SERIE, pe.ID_PERSON
        FROM T_WC_T2S_PERSON_GROUP pg
        INNER JOIN T_WC_T2S_PERSON_EPISODE pe ON pe.ID_PERSON = pg.ID_PERSON AND COALESCE(pe.DELETED, 0) = 0
        WHERE COALESCE(pg.DELETED, 0) = 0
    ) c
    INNER JOIN `T_WC_T2S_GROUP` g ON g.ID_GROUP = c.ID_GROUP
    WHERE g.PERSON_COUNT >= 2
    GROUP BY g.GROUP_SOURCE, c.ID_GROUP, c.ID_SERIE, g.PERSON_COUNT
    HAVING COUNT(DISTINCT c.ID_PERSON) >= 2
       AND COUNT(DISTINCT c.ID_PERSON) / g.PERSON_COUNT >= 0.4
) x
GROUP BY x.GROUP_SOURCE
ORDER BY x.GROUP_SOURCE;
