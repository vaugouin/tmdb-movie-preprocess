SELECT 'D. Monty Python: works, MEMBER_COUNT and the members credited' AS SECTION;

SELECT g.ID_GROUP, g.GROUP_NAME, g.GROUP_SOURCE, g.ID_WIKIDATA, g.PERSON_COUNT,
       (SELECT GROUP_CONCAT(p.PERSON_NAME ORDER BY pg.DISPLAY_ORDER SEPARATOR ', ')
        FROM T_WC_T2S_PERSON_GROUP pg INNER JOIN T_WC_T2S_PERSON p ON p.ID_PERSON = pg.ID_PERSON
        WHERE pg.ID_GROUP = g.ID_GROUP) AS MEMBERS
FROM `T_WC_T2S_GROUP` g
WHERE g.GROUP_NAME LIKE '%Monty Python%';

SELECT 'movie' AS MAJOR, g.GROUP_NAME, gw.DISPLAY_ORDER, m.MOVIE_TITLE AS TITLE, m.DAT_RELEASE AS WORK_DATE,
       gw.IS_GROUP_CREDITED, gw.MEMBER_COUNT, gw.MEMBER_SHARE, gw.CREDIT_KINDS,
       (SELECT GROUP_CONCAT(DISTINCT p.PERSON_NAME ORDER BY p.PERSON_NAME SEPARATOR ', ')
        FROM T_WC_T2S_PERSON_GROUP pg
        INNER JOIN T_WC_T2S_PERSON_MOVIE pm ON pm.ID_PERSON = pg.ID_PERSON AND pm.ID_MOVIE = gw.ID_MOVIE AND COALESCE(pm.DELETED, 0) = 0
        INNER JOIN T_WC_T2S_PERSON p ON p.ID_PERSON = pg.ID_PERSON
        WHERE pg.ID_GROUP = gw.ID_GROUP) AS MEMBERS_CREDITED
FROM T_WC_T2S_GROUP_MOVIE gw
INNER JOIN `T_WC_T2S_GROUP` g ON g.ID_GROUP = gw.ID_GROUP
INNER JOIN T_WC_T2S_MOVIE m ON m.ID_MOVIE = gw.ID_MOVIE
WHERE g.GROUP_NAME LIKE '%Monty Python%'
ORDER BY g.ID_GROUP, gw.DISPLAY_ORDER;

SELECT 'serie' AS MAJOR, g.GROUP_NAME, gw.DISPLAY_ORDER, s.SERIE_TITLE AS TITLE, s.DAT_FIRST_AIR AS WORK_DATE,
       gw.IS_GROUP_CREDITED, gw.MEMBER_COUNT, gw.MEMBER_SHARE, gw.CREDIT_KINDS,
       (SELECT GROUP_CONCAT(DISTINCT p.PERSON_NAME ORDER BY p.PERSON_NAME SEPARATOR ', ')
        FROM T_WC_T2S_PERSON_GROUP pg
        INNER JOIN T_WC_T2S_PERSON p ON p.ID_PERSON = pg.ID_PERSON
        WHERE pg.ID_GROUP = gw.ID_GROUP
          AND (EXISTS (SELECT 1 FROM T_WC_T2S_PERSON_SERIE c WHERE c.ID_PERSON = pg.ID_PERSON AND c.ID_SERIE = gw.ID_SERIE AND COALESCE(c.DELETED, 0) = 0)
            OR EXISTS (SELECT 1 FROM T_WC_T2S_PERSON_SEASON c WHERE c.ID_PERSON = pg.ID_PERSON AND c.ID_SERIE = gw.ID_SERIE AND COALESCE(c.DELETED, 0) = 0)
            OR EXISTS (SELECT 1 FROM T_WC_T2S_PERSON_EPISODE c WHERE c.ID_PERSON = pg.ID_PERSON AND c.ID_SERIE = gw.ID_SERIE AND COALESCE(c.DELETED, 0) = 0))) AS MEMBERS_CREDITED
FROM T_WC_T2S_GROUP_SERIE gw
INNER JOIN `T_WC_T2S_GROUP` g ON g.ID_GROUP = gw.ID_GROUP
INNER JOIN T_WC_T2S_SERIE s ON s.ID_SERIE = gw.ID_SERIE
WHERE g.GROUP_NAME LIKE '%Monty Python%'
ORDER BY g.ID_GROUP, gw.DISPLAY_ORDER;

