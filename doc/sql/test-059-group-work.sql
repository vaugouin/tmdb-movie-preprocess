SELECT 'IS_GROUP_CREDITED rows' AS SECTION;

SELECT (SELECT COUNT(*) FROM T_WC_T2S_GROUP_MOVIE WHERE IS_GROUP_CREDITED = 1) AS MOVIE_GROUP_CREDITED,
       (SELECT COUNT(*) FROM T_WC_T2S_GROUP_MOVIE WHERE IS_GROUP_CREDITED = 1 AND MEMBER_COUNT = 0) AS MOVIE_CREDITED_NO_MEMBER,
       (SELECT COUNT(*) FROM T_WC_T2S_GROUP_SERIE WHERE IS_GROUP_CREDITED = 1) AS SERIE_GROUP_CREDITED,
       (SELECT COUNT(*) FROM T_WC_T2S_GROUP_SERIE WHERE IS_GROUP_CREDITED = 1 AND MEMBER_COUNT = 0) AS SERIE_CREDITED_NO_MEMBER;

