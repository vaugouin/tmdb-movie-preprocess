-- ============================================================================
-- TMDB-MOVIE-PREPROCESS-059 : a group's works, checks after a pass of Process 74
-- ============================================================================
--
-- READ ONLY. Run after the first pass of Process 74 (scope group-works, or main), on a
-- base where doc/sql/migration-t2s-group-work.sql has been applied. Section G does not
-- need the pass: it recomputes the rule from the credits, for every group family.
--
-- THE RULE (Philippe, 2026-10-11): a work attaches to a group when the group's own
-- Wikidata item is credited on it (IS_GROUP_CREDITED = 1), or when MEMBER_COUNT >= 2
-- AND MEMBER_SHARE >= 0.4. Only GROUP_SOURCE 'P463' and 'custom'; 'P108' and 'P54'
-- groups never get works.
--
-- Expectations, written BEFORE the run:
--   A. Rows only for GROUP_SOURCE P463 and custom. Any P108 or P54 row is a bug.
--   B. Integrity: every count of this section must be 0.
--   C. Top groups by works: bands, comedy troupes, families. A university, a studio
--      or a club at the top would mean the P463 family needs a cap too.
--   D. Monty Python: And Now for Something Completely Different, Monty Python and the
--      Holy Grail, Life of Brian, Live at the Hollywood Bowl, The Meaning of Life
--      (movies) and Monty Python's Flying Circus (series).
--   E. The Beatles: A Hard Day's Night and Help! with MEMBER_COUNT 4.
--   F. Pete Best: no work whose only credited Beatle is Pete Best (must be 0).
--   G. Dry run, for the record: what the member rule WOULD attach per GROUP_SOURCE,
--      P108 and P54 included (members only, the group-credit half is not counted).
-- ============================================================================

SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------------
SELECT 'A. Rows per GROUP_SOURCE' AS SECTION;

SELECT 'movie' AS MAJOR, g.GROUP_SOURCE, COUNT(*) AS ROWS_STORED,
       COUNT(DISTINCT gw.ID_GROUP) AS GROUPS_WITH_WORKS,
       SUM(gw.IS_GROUP_CREDITED = 1) AS GROUP_CREDITED,
       SUM(gw.IS_GROUP_CREDITED = 0) AS BY_MEMBERS_ONLY,
       ROUND(AVG(gw.MEMBER_COUNT), 2) AS AVG_MEMBERS,
       ROUND(AVG(gw.MEMBER_SHARE), 3) AS AVG_SHARE
FROM T_WC_T2S_GROUP_MOVIE gw
INNER JOIN `T_WC_T2S_GROUP` g ON g.ID_GROUP = gw.ID_GROUP
GROUP BY g.GROUP_SOURCE
UNION ALL
SELECT 'serie', g.GROUP_SOURCE, COUNT(*),
       COUNT(DISTINCT gw.ID_GROUP),
       SUM(gw.IS_GROUP_CREDITED = 1),
       SUM(gw.IS_GROUP_CREDITED = 0),
       ROUND(AVG(gw.MEMBER_COUNT), 2),
       ROUND(AVG(gw.MEMBER_SHARE), 3)
FROM T_WC_T2S_GROUP_SERIE gw
INNER JOIN `T_WC_T2S_GROUP` g ON g.ID_GROUP = gw.ID_GROUP
GROUP BY g.GROUP_SOURCE;

SELECT 'movie' AS MAJOR, CREDIT_KINDS, COUNT(*) AS ROWS_STORED FROM T_WC_T2S_GROUP_MOVIE GROUP BY CREDIT_KINDS
UNION ALL
SELECT 'serie', CREDIT_KINDS, COUNT(*) FROM T_WC_T2S_GROUP_SERIE GROUP BY CREDIT_KINDS;

-- ---------------------------------------------------------------------------
SELECT 'B. Integrity (every count must be 0)' AS SECTION;

SELECT
  (SELECT COUNT(*) FROM T_WC_T2S_GROUP_MOVIE gw LEFT JOIN `T_WC_T2S_GROUP` g ON g.ID_GROUP = gw.ID_GROUP WHERE g.ID_GROUP IS NULL) AS MOVIE_ORPHAN_GROUP,
  (SELECT COUNT(*) FROM T_WC_T2S_GROUP_MOVIE gw LEFT JOIN T_WC_T2S_MOVIE m ON m.ID_MOVIE = gw.ID_MOVIE WHERE m.ID_MOVIE IS NULL) AS MOVIE_ORPHAN_WORK,
  (SELECT COUNT(*) FROM T_WC_T2S_GROUP_SERIE gw LEFT JOIN `T_WC_T2S_GROUP` g ON g.ID_GROUP = gw.ID_GROUP WHERE g.ID_GROUP IS NULL) AS SERIE_ORPHAN_GROUP,
  (SELECT COUNT(*) FROM T_WC_T2S_GROUP_SERIE gw LEFT JOIN T_WC_T2S_SERIE s ON s.ID_SERIE = gw.ID_SERIE WHERE s.ID_SERIE IS NULL) AS SERIE_ORPHAN_WORK,
  (SELECT COUNT(*) FROM T_WC_T2S_GROUP_MOVIE gw INNER JOIN `T_WC_T2S_GROUP` g ON g.ID_GROUP = gw.ID_GROUP WHERE g.GROUP_SOURCE NOT IN ('P463', 'custom')) AS MOVIE_EXCLUDED_SOURCE,
  (SELECT COUNT(*) FROM T_WC_T2S_GROUP_SERIE gw INNER JOIN `T_WC_T2S_GROUP` g ON g.ID_GROUP = gw.ID_GROUP WHERE g.GROUP_SOURCE NOT IN ('P463', 'custom')) AS SERIE_EXCLUDED_SOURCE,
  (SELECT COUNT(*) FROM T_WC_T2S_GROUP_MOVIE WHERE NOT (IS_GROUP_CREDITED = 1 OR (MEMBER_COUNT >= 2 AND MEMBER_SHARE >= 0.4))) AS MOVIE_OUTSIDE_RULE,
  (SELECT COUNT(*) FROM T_WC_T2S_GROUP_SERIE WHERE NOT (IS_GROUP_CREDITED = 1 OR (MEMBER_COUNT >= 2 AND MEMBER_SHARE >= 0.4))) AS SERIE_OUTSIDE_RULE,
  (SELECT COUNT(*) FROM T_WC_T2S_GROUP_MOVIE WHERE MEMBER_SHARE < 0 OR MEMBER_SHARE > 1 OR DISPLAY_ORDER IS NULL) AS MOVIE_BAD_VALUES,
  (SELECT COUNT(*) FROM T_WC_T2S_GROUP_SERIE WHERE MEMBER_SHARE < 0 OR MEMBER_SHARE > 1 OR DISPLAY_ORDER IS NULL) AS SERIE_BAD_VALUES;

-- ---------------------------------------------------------------------------
SELECT 'C. Top groups by work count' AS SECTION;

SELECT g.ID_GROUP, g.GROUP_NAME, g.GROUP_SOURCE, g.ID_WIKIDATA, g.PERSON_COUNT,
       COALESCE(m.MOVIES, 0) AS MOVIES, COALESCE(s.SERIES, 0) AS SERIES,
       COALESCE(m.MOVIES, 0) + COALESCE(s.SERIES, 0) AS WORKS,
       COALESCE(m.CREDITED, 0) + COALESCE(s.CREDITED, 0) AS GROUP_CREDITED
FROM `T_WC_T2S_GROUP` g
LEFT JOIN (SELECT ID_GROUP, COUNT(*) AS MOVIES, SUM(IS_GROUP_CREDITED) AS CREDITED FROM T_WC_T2S_GROUP_MOVIE GROUP BY ID_GROUP) m ON m.ID_GROUP = g.ID_GROUP
LEFT JOIN (SELECT ID_GROUP, COUNT(*) AS SERIES, SUM(IS_GROUP_CREDITED) AS CREDITED FROM T_WC_T2S_GROUP_SERIE GROUP BY ID_GROUP) s ON s.ID_GROUP = g.ID_GROUP
WHERE m.ID_GROUP IS NOT NULL OR s.ID_GROUP IS NOT NULL
ORDER BY WORKS DESC, g.ID_GROUP
LIMIT 40;

