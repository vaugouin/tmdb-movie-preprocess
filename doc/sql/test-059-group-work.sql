SELECT 'F. Pete Best: works whose only credited Beatle is Pete Best (must be 0)' AS SECTION;

-- A stored Beatles movie where Pete Best is credited and no other member of the group
-- is. Split by IS_GROUP_CREDITED: a 0 on both lines is the expectation; a row with the
-- group credited would be a Wikidata statement worth reading, not a rule failure.
SELECT 'movie' AS MAJOR, gw.IS_GROUP_CREDITED, COUNT(*) AS PETE_BEST_ONLY_WORKS
FROM T_WC_T2S_GROUP_MOVIE gw
INNER JOIN `T_WC_T2S_GROUP` g ON g.ID_GROUP = gw.ID_GROUP AND g.GROUP_NAME LIKE '%Beatles%'
WHERE EXISTS (SELECT 1 FROM T_WC_T2S_PERSON_GROUP pg
              INNER JOIN T_WC_T2S_PERSON p ON p.ID_PERSON = pg.ID_PERSON AND p.PERSON_NAME = 'Pete Best'
              INNER JOIN T_WC_T2S_PERSON_MOVIE pm ON pm.ID_PERSON = pg.ID_PERSON AND pm.ID_MOVIE = gw.ID_MOVIE AND COALESCE(pm.DELETED, 0) = 0
              WHERE pg.ID_GROUP = gw.ID_GROUP)
  AND NOT EXISTS (SELECT 1 FROM T_WC_T2S_PERSON_GROUP pg
                  INNER JOIN T_WC_T2S_PERSON p ON p.ID_PERSON = pg.ID_PERSON AND p.PERSON_NAME <> 'Pete Best'
                  INNER JOIN T_WC_T2S_PERSON_MOVIE pm ON pm.ID_PERSON = pg.ID_PERSON AND pm.ID_MOVIE = gw.ID_MOVIE AND COALESCE(pm.DELETED, 0) = 0
                  WHERE pg.ID_GROUP = gw.ID_GROUP)
GROUP BY gw.IS_GROUP_CREDITED
UNION ALL
SELECT 'serie', gw.IS_GROUP_CREDITED, COUNT(*)
FROM T_WC_T2S_GROUP_SERIE gw
INNER JOIN `T_WC_T2S_GROUP` g ON g.ID_GROUP = gw.ID_GROUP AND g.GROUP_NAME LIKE '%Beatles%'
WHERE gw.MEMBER_COUNT = 1
  AND EXISTS (SELECT 1 FROM T_WC_T2S_PERSON_GROUP pg
              INNER JOIN T_WC_T2S_PERSON p ON p.ID_PERSON = pg.ID_PERSON AND p.PERSON_NAME = 'Pete Best'
              WHERE pg.ID_GROUP = gw.ID_GROUP
                AND (EXISTS (SELECT 1 FROM T_WC_T2S_PERSON_SERIE c WHERE c.ID_PERSON = pg.ID_PERSON AND c.ID_SERIE = gw.ID_SERIE AND COALESCE(c.DELETED, 0) = 0)
                  OR EXISTS (SELECT 1 FROM T_WC_T2S_PERSON_SEASON c WHERE c.ID_PERSON = pg.ID_PERSON AND c.ID_SERIE = gw.ID_SERIE AND COALESCE(c.DELETED, 0) = 0)
                  OR EXISTS (SELECT 1 FROM T_WC_T2S_PERSON_EPISODE c WHERE c.ID_PERSON = pg.ID_PERSON AND c.ID_SERIE = gw.ID_SERIE AND COALESCE(c.DELETED, 0) = 0)))
GROUP BY gw.IS_GROUP_CREDITED;

