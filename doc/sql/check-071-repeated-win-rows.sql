-- TMDB-MOVIE-PREPROCESS-071, win rows repeated for the same year: series 688 has four win rows
-- of award 14174 (Screen Actors Guild ensemble, drama series) for two years, 2001 and 2002.
-- Are they duplicates of the build or distinct Wikidata statements? Read-only.

SELECT '=== 1. the win rows of series 688 on award 14174, with their Wikidata statement ===' AS section;
SELECT w.ID_ROW, w.ID_STATEMENT, w.AWARD_YEAR, w.ID_CEREMONY_WIKIDATA, w.DELETED, w.DISPLAY_ORDER,
       st.ID_WIKIDATA, st.ID_PROPERTY, st.STATEMENT_GUID, st.RANK, st.DELETED AS ST_DELETED
FROM T_WC_T2S_SERIE_AWARD w
LEFT JOIN T_WC_WIKIDATA_STATEMENT st ON st.ID_STATEMENT = w.ID_STATEMENT
WHERE w.ID_SERIE = 688 AND w.ID_AWARD = 14174
ORDER BY w.AWARD_YEAR, w.ID_ROW;

SELECT '=== 2. the qualifiers of these statements ===' AS section;
SELECT w.ID_ROW, w.ID_STATEMENT, q.ID_QUALIFIER_PROPERTY, q.VALUE_TYPE, q.DELETED AS Q_DELETED,
       qi.ID_ITEM, qt.YEAR_VALUE, qt.DATE_START
FROM T_WC_T2S_SERIE_AWARD w
INNER JOIN T_WC_WIKIDATA_STATEMENT_QUALIFIER q ON q.ID_STATEMENT = w.ID_STATEMENT
LEFT JOIN T_WC_WIKIDATA_QUALIFIER_ITEM_VALUE qi ON qi.ID_STATEMENT_QUALIFIER = q.ID_STATEMENT_QUALIFIER
LEFT JOIN T_WC_WIKIDATA_QUALIFIER_TIME_VALUE qt ON qt.ID_STATEMENT_QUALIFIER = q.ID_STATEMENT_QUALIFIER
WHERE w.ID_SERIE = 688 AND w.ID_AWARD = 14174
ORDER BY w.AWARD_YEAR, w.ID_ROW, q.ID_QUALIFIER_PROPERTY, q.DISPLAY_ORDER;

SELECT '=== 3. how common: (entity, award, year) groups holding more than one live win row ===' AS section;
SELECT 'movie' AS entity, COUNT(*) AS groups_repeated, SUM(n) AS rows_in_them, SUM(n - statements) AS rows_sharing_a_statement
FROM (SELECT COUNT(*) AS n, COUNT(DISTINCT ID_STATEMENT) AS statements FROM T_WC_T2S_MOVIE_AWARD
      WHERE DELETED = 0 AND AWARD_YEAR IS NOT NULL GROUP BY ID_MOVIE, ID_AWARD, AWARD_YEAR HAVING COUNT(*) > 1) g
UNION ALL
SELECT 'serie', COUNT(*), SUM(n), SUM(n - statements)
FROM (SELECT COUNT(*) AS n, COUNT(DISTINCT ID_STATEMENT) AS statements FROM T_WC_T2S_SERIE_AWARD
      WHERE DELETED = 0 AND AWARD_YEAR IS NOT NULL GROUP BY ID_SERIE, ID_AWARD, AWARD_YEAR HAVING COUNT(*) > 1) g
UNION ALL
SELECT 'person, same work', COUNT(*), SUM(n), SUM(n - statements)
FROM (SELECT COUNT(*) AS n, COUNT(DISTINCT ID_STATEMENT) AS statements FROM T_WC_T2S_PERSON_AWARD
      WHERE DELETED = 0 AND AWARD_YEAR IS NOT NULL
      GROUP BY ID_PERSON, ID_AWARD, AWARD_YEAR, COALESCE(ID_MOVIE_FOR, 0), COALESCE(ID_SERIE_FOR, 0) HAVING COUNT(*) > 1) g;

SELECT '=== 4. totals of live win rows, for scale ===' AS section;
SELECT (SELECT COUNT(*) FROM T_WC_T2S_MOVIE_AWARD WHERE DELETED = 0) AS movie_rows,
       (SELECT COUNT(*) FROM T_WC_T2S_SERIE_AWARD WHERE DELETED = 0) AS serie_rows,
       (SELECT COUNT(*) FROM T_WC_T2S_PERSON_AWARD WHERE DELETED = 0) AS person_rows;

SELECT '=== 5. the ten series groups with the most rows for one year ===' AS section;
SELECT w.ID_SERIE, s.SERIE_TITLE, w.ID_AWARD, a.AWARD_NAME, w.AWARD_YEAR, COUNT(*) AS n, COUNT(DISTINCT w.ID_STATEMENT) AS statements
FROM T_WC_T2S_SERIE_AWARD w
INNER JOIN T_WC_T2S_SERIE s ON s.ID_SERIE = w.ID_SERIE
INNER JOIN T_WC_T2S_AWARD a ON a.ID_AWARD = w.ID_AWARD
WHERE w.DELETED = 0 AND w.AWARD_YEAR IS NOT NULL
GROUP BY w.ID_SERIE, s.SERIE_TITLE, w.ID_AWARD, a.AWARD_NAME, w.AWARD_YEAR
HAVING COUNT(*) > 1
ORDER BY n DESC, w.ID_SERIE
LIMIT 10;
