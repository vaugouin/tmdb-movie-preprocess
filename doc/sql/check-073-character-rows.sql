-- check-073-character-rows.sql
-- TMDB-MOVIE-PREPROCESS-073: the measure of 2026-11-14 returned no row for T_WC_T2S_CHARACTER.
-- Read-only: rows by DELETED value, rows with a QID, where the QID lives in V2.
SELECT NOW() AS NOW_;

SELECT 'A. rows by DELETED' AS STEP, DELETED, COUNT(*) AS N,
       SUM(NULLIF(ID_WIKIDATA, '') IS NOT NULL) AS WITH_QID,
       SUM(NULLIF(WIKIDATA_NAME, '') IS NOT NULL) AS WITH_WIKIDATA_NAME,
       MAX(TIM_UPDATED) AS LAST_UPDATE
FROM T_WC_T2S_CHARACTER GROUP BY DELETED ORDER BY DELETED;

SELECT 'B. QID location' AS STEP, COUNT(*) AS WITH_QID,
       SUM(EXISTS (SELECT 1 FROM T_WC_WIKIDATA_CHARACTER w WHERE w.ID_WIKIDATA = c.ID_WIKIDATA)) AS IN_CHARACTER,
       SUM(EXISTS (SELECT 1 FROM T_WC_WIKIDATA_ITEM w WHERE w.ID_WIKIDATA = c.ID_WIKIDATA)) AS IN_ITEM
FROM T_WC_T2S_CHARACTER c WHERE NULLIF(c.ID_WIKIDATA, '') IS NOT NULL;

SELECT 'C. sample' AS STEP, ID_CHARACTER, CAST_CHARACTER, ID_WIKIDATA, WIKIDATA_NAME, DELETED, MOVIE_COUNT
FROM T_WC_T2S_CHARACTER ORDER BY COALESCE(MOVIE_COUNT, 0) DESC LIMIT 10;
