-- TMDB-MOVIE-PREPROCESS-071, pre-build check (2026-11-10). Read only: SELECT and SHOW.
-- Voie 1:
--   ssh vps-agent pull tmdb-movie-preprocess
--   ssh vps-agent run tmdb-movie-preprocess/doc/sql/check-071-prebuild.sql
--
-- What it settles before the code is written:
--   A. the live definition of the four award tables (against doc/sql/T2S-tables.sql);
--   B. the indexes the win query leans on (qualifier tables);
--   C. the size of the job: link rows today, biggest awards, statements per award;
--   D. the ids the three new evaluations assert (text2sql-eval, new-evaluations-071-*.sql).

SELECT '=== A. live definition of the award tables ===' AS section;

SHOW CREATE TABLE T_WC_T2S_AWARD;
SHOW CREATE TABLE T_WC_T2S_MOVIE_AWARD;
SHOW CREATE TABLE T_WC_T2S_PERSON_AWARD;
SHOW CREATE TABLE T_WC_T2S_SERIE_AWARD;

SELECT '=== B. indexes of the tables the win query reads ===' AS section;

SELECT TABLE_NAME, INDEX_NAME, GROUP_CONCAT(COLUMN_NAME ORDER BY SEQ_IN_INDEX SEPARATOR ', ') AS COLUMNS_IN_ORDER, MAX(NON_UNIQUE) AS NON_UNIQUE
FROM information_schema.STATISTICS
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME IN ('T_WC_WIKIDATA_STATEMENT', 'T_WC_WIKIDATA_ITEM_VALUE', 'T_WC_WIKIDATA_TIME_VALUE',
                     'T_WC_WIKIDATA_STATEMENT_QUALIFIER', 'T_WC_WIKIDATA_QUALIFIER_TIME_VALUE', 'T_WC_WIKIDATA_QUALIFIER_ITEM_VALUE')
GROUP BY TABLE_NAME, INDEX_NAME
ORDER BY TABLE_NAME, INDEX_NAME;

SELECT '=== C1. link rows today ===' AS section;

SELECT 'T_WC_T2S_MOVIE_AWARD' AS TABLE_NAME, COUNT(*) AS LINK_ROWS, MAX(ID_ROW) AS MAX_ID_ROW, COUNT(DISTINCT ID_AWARD) AS AWARDS FROM T_WC_T2S_MOVIE_AWARD
UNION ALL
SELECT 'T_WC_T2S_PERSON_AWARD', COUNT(*), MAX(ID_ROW), COUNT(DISTINCT ID_AWARD) FROM T_WC_T2S_PERSON_AWARD
UNION ALL
SELECT 'T_WC_T2S_SERIE_AWARD', COUNT(*), MAX(ID_ROW), COUNT(DISTINCT ID_AWARD) FROM T_WC_T2S_SERIE_AWARD;

SELECT '=== C2. award rows by source and type ===' AS section;

SELECT AWARD_SOURCE, AWARD_TYPE, COUNT(*) AS AWARD_ROWS, MAX(ID_AWARD) AS MAX_ID_AWARD
FROM T_WC_T2S_AWARD
GROUP BY AWARD_SOURCE, AWARD_TYPE
ORDER BY AWARD_SOURCE, AWARD_TYPE;

SELECT '=== C3. the 10 awards with the most person rows ===' AS section;

SELECT a.ID_AWARD, a.ID_WIKIDATA, a.AWARD_NAME, a.AWARD_SOURCE, COUNT(*) AS PERSON_ROWS
FROM T_WC_T2S_PERSON_AWARD pa
JOIN T_WC_T2S_AWARD a ON a.ID_AWARD = pa.ID_AWARD
GROUP BY a.ID_AWARD, a.ID_WIKIDATA, a.AWARD_NAME, a.AWARD_SOURCE
ORDER BY PERSON_ROWS DESC
LIMIT 10;

SELECT '=== C4. the family rows the build will look for: are they award rows already? ===' AS section;

SELECT a.ID_AWARD, a.ID_WIKIDATA, a.AWARD_NAME, a.AWARD_SOURCE, a.AWARD_TYPE, a.MOVIE_COUNT, a.SERIE_COUNT, a.PERSON_COUNT
FROM T_WC_T2S_AWARD a
WHERE a.ID_WIKIDATA IN ('Q19020', 'Q103618', 'Q102427', 'Q103360', 'Q645595', 'Q1011547', 'Q1044427', 'Q123737')
ORDER BY a.ID_WIKIDATA, a.AWARD_SOURCE;

SELECT '=== D1. Katharine Hepburn and the four films of her Oscars ===' AS section;

SELECT ID_PERSON, PERSON_NAME, ID_WIKIDATA FROM T_WC_T2S_PERSON WHERE ID_WIKIDATA = 'Q56016';

SELECT ID_MOVIE, MOVIE_TITLE, ID_WIKIDATA
FROM T_WC_T2S_MOVIE
WHERE ID_WIKIDATA IN ('Q572789', 'Q736969', 'Q1195311', 'Q451603')
ORDER BY ID_WIKIDATA, ID_MOVIE;

SELECT '=== D2. Academy Award for Best Actress: winners with a year from 1975 to 1990 ===' AS section;

SELECT qt.YEAR_VALUE AS AWARD_YEAR, pe.ID_PERSON, pe.PERSON_NAME
FROM T_WC_T2S_AWARD a
JOIN T_WC_WIKIDATA_ITEM_VALUE v ON v.ID_ITEM = a.ID_WIKIDATA
JOIN T_WC_WIKIDATA_STATEMENT s ON s.ID_STATEMENT = v.ID_STATEMENT AND s.ID_PROPERTY = 'P166'
     AND (s.`RANK` IS NULL OR s.`RANK` <> 'deprecated')
JOIN T_WC_T2S_PERSON pe ON pe.ID_WIKIDATA = s.ID_WIKIDATA
JOIN T_WC_WIKIDATA_STATEMENT_QUALIFIER q ON q.ID_STATEMENT = s.ID_STATEMENT AND q.ID_QUALIFIER_PROPERTY = 'P585'
JOIN T_WC_WIKIDATA_QUALIFIER_TIME_VALUE qt ON qt.ID_STATEMENT_QUALIFIER = q.ID_STATEMENT_QUALIFIER
WHERE a.AWARD_NAME = 'Academy Award for Best Actress' AND a.AWARD_SOURCE = 'P166'
  AND qt.YEAR_VALUE BETWEEN 1975 AND 1990
ORDER BY qt.YEAR_VALUE, pe.ID_PERSON;

SELECT '=== D3. Cesar Award for Best Film (Q645595): the 2010 and 2012 winners among T2S movies ===' AS section;

SELECT qt.YEAR_VALUE AS AWARD_YEAR, m.ID_MOVIE, m.MOVIE_TITLE
FROM T_WC_WIKIDATA_ITEM_VALUE v
JOIN T_WC_WIKIDATA_STATEMENT s ON s.ID_STATEMENT = v.ID_STATEMENT AND s.ID_PROPERTY = 'P166'
     AND (s.`RANK` IS NULL OR s.`RANK` <> 'deprecated')
JOIN T_WC_T2S_MOVIE m ON m.ID_WIKIDATA = s.ID_WIKIDATA
JOIN T_WC_WIKIDATA_STATEMENT_QUALIFIER q ON q.ID_STATEMENT = s.ID_STATEMENT AND q.ID_QUALIFIER_PROPERTY = 'P585'
JOIN T_WC_WIKIDATA_QUALIFIER_TIME_VALUE qt ON qt.ID_STATEMENT_QUALIFIER = q.ID_STATEMENT_QUALIFIER
WHERE v.ID_ITEM = 'Q645595' AND qt.YEAR_VALUE IN (2010, 2012)
ORDER BY qt.YEAR_VALUE, m.ID_MOVIE;

SELECT '=== D4. the award evaluations already in the bank that the family rule will move ===' AS section;

SELECT ID_T2S_EVALUATION, QUESTION, ID_T2S_EVALUATION_CATEGORY, RESOLUTION_MODE, ASSERTIONS_QUERY_RESULT
FROM T_WC_T2S_EVALUATION
WHERE ID_T2S_EVALUATION IN (2313, 2349) OR (DELETED = 0 AND (QUESTION LIKE '%Oscar%' OR QUESTION LIKE '%Academy Award%' OR QUESTION LIKE '%César%'))
ORDER BY ID_T2S_EVALUATION;
