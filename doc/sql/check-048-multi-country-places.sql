-- TMDB-MOVIE-PREPROCESS-048 follow-up: places that sit under several countries at once.
--
-- Read-only, voie 1. Written 2026-10-21 after the acceptance of FASTAPI-TEXT2SQL-335: the
-- France sheet (contained scope) lists 51 movies through "Appalachian Mountains", whose
-- Wikidata country (P17) includes France for Saint-Pierre-and-Miquelon, and 61 through the
-- Mediterranean Sea. A mountain range, a sea or a river spread over several countries is
-- "located in" each of them, which does not make it a place inside each of them for a sheet.
-- This file sizes the effect before any change: which places have two country ancestors or
-- more, by type, and how many works they add to the country sheets.
-- A country is a place with the LOCATION_TYPE of France (ID_LOCATION 126).

SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;

SELECT '1. Type of France' AS SECTION;

SELECT ID_LOCATION, LOCATION_NAME, LOCATION_TYPE FROM T_WC_T2S_LOCATION WHERE ID_LOCATION = 126;

DROP TEMPORARY TABLE IF EXISTS tmp_multi;
CREATE TEMPORARY TABLE tmp_multi (ID_LOCATION INT NOT NULL PRIMARY KEY, N_COUNTRIES INT NOT NULL) ENGINE=InnoDB;
INSERT INTO tmp_multi
SELECT a.ID_LOCATION, COUNT(DISTINCT a.ID_ANCESTOR)
FROM T_WC_T2S_LOCATION_ANCESTOR a
JOIN T_WC_T2S_LOCATION c ON c.ID_LOCATION = a.ID_ANCESTOR AND c.DELETED = 0
JOIN T_WC_T2S_LOCATION l ON l.ID_LOCATION = a.ID_LOCATION AND l.DELETED = 0
WHERE a.DEPTH > 0 AND c.LOCATION_TYPE = (SELECT LOCATION_TYPE FROM T_WC_T2S_LOCATION WHERE ID_LOCATION = 126)
GROUP BY a.ID_LOCATION
HAVING COUNT(DISTINCT a.ID_ANCESTOR) >= 2;

SELECT '2. Places under two countries or more, by type' AS SECTION;

SELECT l.LOCATION_TYPE, COUNT(*) AS PLACES, SUM(l.MOVIE_COUNT) AS MOVIE_LINKS, SUM(l.SERIE_COUNT) AS SERIE_LINKS,
       MAX(t.N_COUNTRIES) AS MAX_COUNTRIES
FROM tmp_multi t JOIN T_WC_T2S_LOCATION l ON l.ID_LOCATION = t.ID_LOCATION
GROUP BY l.LOCATION_TYPE ORDER BY PLACES DESC;

SELECT '2b. The forty best known' AS SECTION;

SELECT l.ID_LOCATION, l.ID_WIKIDATA, l.LOCATION_NAME, l.LOCATION_TYPE, t.N_COUNTRIES, l.MOVIE_COUNT, l.SERIE_COUNT,
       (SELECT GROUP_CONCAT(c.LOCATION_NAME ORDER BY c.LOCATION_NAME SEPARATOR ', ')
          FROM T_WC_T2S_LOCATION_ANCESTOR a JOIN T_WC_T2S_LOCATION c ON c.ID_LOCATION = a.ID_ANCESTOR
         WHERE a.ID_LOCATION = l.ID_LOCATION AND a.DEPTH > 0
           AND c.LOCATION_TYPE = (SELECT LOCATION_TYPE FROM T_WC_T2S_LOCATION WHERE ID_LOCATION = 126)) AS COUNTRIES
FROM tmp_multi t JOIN T_WC_T2S_LOCATION l ON l.ID_LOCATION = t.ID_LOCATION
ORDER BY l.MOVIE_COUNT + l.SERIE_COUNT DESC
LIMIT 40;

SELECT '3. France: movies on the sheet only through a multi-country place, per role' AS SECTION;

SELECT j.LOCATION_ROLE,
       COUNT(DISTINCT j.ID_MOVIE) AS ALL_CONTAINED,
       COUNT(DISTINCT CASE WHEN t.ID_LOCATION IS NULL THEN j.ID_MOVIE END) AS WITHOUT_MULTI_COUNTRY
FROM T_WC_T2S_LOCATION_ANCESTOR a
JOIN T_WC_T2S_MOVIE_LOCATION j ON j.ID_LOCATION = a.ID_LOCATION AND COALESCE(j.DELETED, 0) = 0
JOIN T_WC_T2S_MOVIE m ON m.ID_MOVIE = j.ID_MOVIE AND COALESCE(m.DELETED, 0) = 0
LEFT JOIN tmp_multi t ON t.ID_LOCATION = j.ID_LOCATION
WHERE a.ID_ANCESTOR = 126
GROUP BY j.LOCATION_ROLE;

SELECT '4. Every country: movies added through multi-country places (top 15)' AS SECTION;

SELECT c.ID_LOCATION, c.LOCATION_NAME,
       COUNT(DISTINCT j.ID_MOVIE) AS ALL_CONTAINED,
       COUNT(DISTINCT CASE WHEN t.ID_LOCATION IS NULL THEN j.ID_MOVIE END) AS WITHOUT_MULTI_COUNTRY
FROM T_WC_T2S_LOCATION c
JOIN T_WC_T2S_LOCATION_ANCESTOR a ON a.ID_ANCESTOR = c.ID_LOCATION
JOIN T_WC_T2S_MOVIE_LOCATION j ON j.ID_LOCATION = a.ID_LOCATION AND COALESCE(j.DELETED, 0) = 0
LEFT JOIN tmp_multi t ON t.ID_LOCATION = j.ID_LOCATION
WHERE c.DELETED = 0 AND c.LOCATION_TYPE = (SELECT LOCATION_TYPE FROM T_WC_T2S_LOCATION WHERE ID_LOCATION = 126)
GROUP BY c.ID_LOCATION, c.LOCATION_NAME
ORDER BY ALL_CONTAINED - WITHOUT_MULTI_COUNTRY DESC
LIMIT 15;

DROP TEMPORARY TABLE IF EXISTS tmp_multi;
