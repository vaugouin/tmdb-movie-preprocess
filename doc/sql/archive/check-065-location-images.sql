-- TMDB-MOVIE-PREPROCESS-065 (to open): why location cards show no picture.
-- READ-ONLY. tmdb-front and voice-agent read POSTER_PATH then WIKIPEDIA_IMAGE_PATH; process 72
-- never writes WIKIPEDIA_IMAGE_PATH, process 71 writes WIKIPEDIA_MAIN_IMAGE_URL(_FR).
SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;

SELECT '1. Los Angeles' AS SECTION;
SELECT ID_LOCATION, ID_WIKIDATA, LOCATION_NAME, POSTER_PATH, WIKIPEDIA_IMAGE_PATH,
       WIKIPEDIA_MAIN_IMAGE_URL, WIKIPEDIA_MAIN_IMAGE_URL_FR
FROM T_WC_T2S_LOCATION WHERE ID_WIKIDATA = 'Q65';

SELECT '2. Living places: image coverage' AS SECTION;
SELECT COUNT(*) AS LIEUX,
       SUM(WIKIPEDIA_IMAGE_PATH IS NOT NULL AND WIKIPEDIA_IMAGE_PATH <> '') AS IMAGE_PATH,
       SUM(WIKIPEDIA_MAIN_IMAGE_URL IS NOT NULL AND WIKIPEDIA_MAIN_IMAGE_URL <> '') AS MAIN_URL_EN,
       SUM(WIKIPEDIA_MAIN_IMAGE_URL_FR IS NOT NULL AND WIKIPEDIA_MAIN_IMAGE_URL_FR <> '') AS MAIN_URL_FR,
       SUM((WIKIPEDIA_MAIN_IMAGE_URL IS NULL OR WIKIPEDIA_MAIN_IMAGE_URL = '')
           AND WIKIPEDIA_MAIN_IMAGE_URL_FR IS NOT NULL AND WIKIPEDIA_MAIN_IMAGE_URL_FR <> '') AS FR_ONLY,
       SUM(EXISTS (SELECT 1 FROM T_WC_WIKIPEDIA_PAGE_LANG p
                   WHERE p.ID_WIKIDATA = l.ID_WIKIDATA AND p.LANG = 'en')) AS PAGE_EN_CRAWLED
FROM T_WC_T2S_LOCATION l
WHERE DELETED = 0;

SELECT '3. Places with the most works and no English image' AS SECTION;
SELECT ID_LOCATION, ID_WIKIDATA, LOCATION_NAME, LOCATION_TYPE, MOVIE_COUNT, SERIE_COUNT,
       WIKIPEDIA_MAIN_IMAGE_URL_FR IS NOT NULL AS HAS_FR
FROM T_WC_T2S_LOCATION
WHERE DELETED = 0 AND (WIKIPEDIA_MAIN_IMAGE_URL IS NULL OR WIKIPEDIA_MAIN_IMAGE_URL = '')
ORDER BY COALESCE(MOVIE_COUNT, 0) + COALESCE(SERIE_COUNT, 0) DESC
LIMIT 15;
