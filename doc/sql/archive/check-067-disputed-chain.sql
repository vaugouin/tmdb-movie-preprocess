-- TMDB-MOVIE-PREPROCESS-067: do the towns of a disputed territory reach it through P131?
-- Decision of Philippe, 2026-10-21: a disputed territory goes under each claimed country.
-- Jerusalem, Crimea, the West Bank carry P31 Q15239622 (disputed territory), Yalta,
-- Sevastopol, Simferopol do not (check-067-disputed-signals-20261021.txt). If their P131
-- chain reaches an item with that class, the rule can say "a place inside a disputed
-- territory is disputed" without a list of names.
--
-- Read-only, voie 1. Written 2026-10-21.

SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;

SELECT '1. P131 parents (two levels) of the disputed towns, with their P31' AS SECTION;

SELECT c.ID_WIKIDATA AS CHILD, cl.LABEL_EN AS CHILD_LABEL, v1.ID_ITEM AS P131_1, p1.LABEL_EN AS P131_1_LABEL,
       (SELECT GROUP_CONCAT(DISTINCT COALESCE(k.LABEL_EN, x.ID_ITEM) ORDER BY 1 SEPARATOR ', ')
          FROM T_WC_WIKIDATA_STATEMENT s JOIN T_WC_WIKIDATA_ITEM_VALUE x ON x.ID_STATEMENT = s.ID_STATEMENT
          LEFT JOIN T_WC_WIKIDATA_ITEM k ON k.ID_WIKIDATA = x.ID_ITEM
         WHERE s.ID_WIKIDATA = v1.ID_ITEM AND s.ID_PROPERTY = 'P31' AND s.DELETED = 0) AS P131_1_P31,
       (SELECT GROUP_CONCAT(DISTINCT CONCAT(x.ID_ITEM, ' ', COALESCE(k.LABEL_EN, '?')) ORDER BY 1 SEPARATOR ', ')
          FROM T_WC_WIKIDATA_STATEMENT s JOIN T_WC_WIKIDATA_ITEM_VALUE x ON x.ID_STATEMENT = s.ID_STATEMENT
          LEFT JOIN T_WC_WIKIDATA_ITEM k ON k.ID_WIKIDATA = x.ID_ITEM
         WHERE s.ID_WIKIDATA = v1.ID_ITEM AND s.ID_PROPERTY = 'P131' AND s.DELETED = 0) AS P131_2
FROM (SELECT 'Q128499' AS ID_WIKIDATA UNION ALL SELECT 'Q7525' UNION ALL SELECT 'Q19566' UNION ALL SELECT 'Q46001'
      UNION ALL SELECT 'Q4409143' UNION ALL SELECT 'Q178168' UNION ALL SELECT 'Q47837' UNION ALL SELECT 'Q211318'
      UNION ALL SELECT 'Q644636' UNION ALL SELECT 'Q83210' UNION ALL SELECT 'Q407199' UNION ALL SELECT 'Q1032254'
      UNION ALL SELECT 'Q331990' UNION ALL SELECT 'Q708640') c
LEFT JOIN T_WC_WIKIDATA_ITEM cl ON cl.ID_WIKIDATA = c.ID_WIKIDATA
LEFT JOIN T_WC_WIKIDATA_STATEMENT st ON st.ID_WIKIDATA = c.ID_WIKIDATA AND st.ID_PROPERTY = 'P131' AND st.DELETED = 0
LEFT JOIN T_WC_WIKIDATA_ITEM_VALUE v1 ON v1.ID_STATEMENT = st.ID_STATEMENT
LEFT JOIN T_WC_WIKIDATA_ITEM p1 ON p1.ID_WIKIDATA = v1.ID_ITEM
ORDER BY cl.LABEL_EN;

SELECT '2. P31 of the same places' AS SECTION;

SELECT c.ID_WIKIDATA, cl.LABEL_EN,
       (SELECT GROUP_CONCAT(DISTINCT CONCAT(x.ID_ITEM, ' ', COALESCE(k.LABEL_EN, '?')) ORDER BY 1 SEPARATOR ', ')
          FROM T_WC_WIKIDATA_STATEMENT s JOIN T_WC_WIKIDATA_ITEM_VALUE x ON x.ID_STATEMENT = s.ID_STATEMENT
          LEFT JOIN T_WC_WIKIDATA_ITEM k ON k.ID_WIKIDATA = x.ID_ITEM
         WHERE s.ID_WIKIDATA = c.ID_WIKIDATA AND s.ID_PROPERTY = 'P31' AND s.DELETED = 0) AS P31
FROM (SELECT 'Q4409143' AS ID_WIKIDATA UNION ALL SELECT 'Q178168' UNION ALL SELECT 'Q47837' UNION ALL SELECT 'Q211318'
      UNION ALL SELECT 'Q644636' UNION ALL SELECT 'Q83210' UNION ALL SELECT 'Q407199' UNION ALL SELECT 'Q1032254'
      UNION ALL SELECT 'Q331990' UNION ALL SELECT 'Q708640' UNION ALL SELECT 'Q23334' UNION ALL SELECT 'Q43100') c
LEFT JOIN T_WC_WIKIDATA_ITEM cl ON cl.ID_WIKIDATA = c.ID_WIKIDATA;
