-- TMDB-MOVIE-PREPROCESS-067: what the database knows about the P17 parents, to tell a
-- historical state (Tokugawa shogunate, Nazi Germany) from a living country.
--
-- Read-only, voie 1. Written 2026-10-21. test-067-cross-border-places-20261021.txt found no
-- P582 qualifier on the P17 / P131 edges (2 of 510 974) and no P576 on their parents. This
-- file asks why: are the parents crawled at all (statements, item row), and which property
-- would separate the two kinds (P576, P31 "historical country" Q3024240, "former country"
-- Q1250464...).

SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;

SELECT '1. P576 and P582 in the whole statement store' AS SECTION;

SELECT (SELECT COUNT(*) FROM T_WC_WIKIDATA_STATEMENT WHERE ID_PROPERTY = 'P576' AND DELETED = 0) AS P576_STATEMENTS,
       (SELECT COUNT(*) FROM T_WC_WIKIDATA_STATEMENT_QUALIFIER WHERE ID_QUALIFIER_PROPERTY = 'P582' AND COALESCE(DELETED, 0) = 0) AS P582_QUALIFIERS,
       (SELECT COUNT(DISTINCT ID_PROPERTY) FROM T_WC_WIKIDATA_STATEMENT WHERE DELETED = 0) AS DISTINCT_PROPERTIES;

SELECT '2. The P17 parents: items, statements, P31' AS SECTION;

DROP TEMPORARY TABLE IF EXISTS tmp_p;
CREATE TEMPORARY TABLE tmp_p (ID_ITEM VARCHAR(50) NOT NULL PRIMARY KEY, N_CHILDREN INT NOT NULL)
  ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
INSERT INTO tmp_p
SELECT iv.ID_ITEM, COUNT(*)
FROM T_WC_WIKIDATA_STATEMENT st
JOIN T_WC_WIKIDATA_ITEM_VALUE iv ON iv.ID_STATEMENT = st.ID_STATEMENT
WHERE st.ID_PROPERTY = 'P17' AND st.DELETED = 0
GROUP BY iv.ID_ITEM;

SELECT COUNT(*) AS P17_PARENTS,
       SUM(EXISTS (SELECT 1 FROM T_WC_WIKIDATA_ITEM wi WHERE wi.ID_WIKIDATA = p.ID_ITEM)) AS WITH_ITEM_ROW,
       SUM(EXISTS (SELECT 1 FROM T_WC_WIKIDATA_STATEMENT s WHERE s.ID_WIKIDATA = p.ID_ITEM AND s.DELETED = 0)) AS WITH_STATEMENTS,
       SUM(EXISTS (SELECT 1 FROM T_WC_WIKIDATA_STATEMENT s WHERE s.ID_WIKIDATA = p.ID_ITEM AND s.ID_PROPERTY = 'P31' AND s.DELETED = 0)) AS WITH_P31
FROM tmp_p p;

SELECT '3. Witness parents: living and historical' AS SECTION;

SELECT p.ID_ITEM, wi.LABEL_EN, p.N_CHILDREN,
       (SELECT COUNT(*) FROM T_WC_WIKIDATA_STATEMENT s WHERE s.ID_WIKIDATA = p.ID_ITEM AND s.DELETED = 0) AS STATEMENTS,
       (SELECT GROUP_CONCAT(DISTINCT iv.ID_ITEM ORDER BY iv.ID_ITEM SEPARATOR ' ')
          FROM T_WC_WIKIDATA_STATEMENT s JOIN T_WC_WIKIDATA_ITEM_VALUE iv ON iv.ID_STATEMENT = s.ID_STATEMENT
         WHERE s.ID_WIKIDATA = p.ID_ITEM AND s.ID_PROPERTY = 'P31' AND s.DELETED = 0) AS P31,
       LEFT(JSON_UNQUOTE(JSON_EXTRACT(wi.DESCRIPTIONS_JSON, '$.en')), 60) AS DESCRIPTION_EN
FROM tmp_p p
LEFT JOIN T_WC_WIKIDATA_ITEM wi ON wi.ID_WIKIDATA = p.ID_ITEM
WHERE p.ID_ITEM IN ('Q142', 'Q145', 'Q869', 'Q17', 'Q183', 'Q212', 'Q159', 'Q801', 'Q219060',
                    'Q193681', 'Q7318', 'Q36704', 'Q12560', 'Q28513', 'Q1062422', 'Q1115291', 'Q1155700', 'Q841364',
                    'Q2277', 'Q156111', 'Q713750', 'Q2415901', 'Q15180', 'Q1747689', 'Q188712', 'Q16410');

SELECT '4. Is there a P31 class shared by the historical ones? Most frequent P31 among P17 parents' AS SECTION;

SELECT iv.ID_ITEM AS P31_CLASS, wi.LABEL_EN, COUNT(DISTINCT p.ID_ITEM) AS PARENTS
FROM tmp_p p
JOIN T_WC_WIKIDATA_STATEMENT s ON s.ID_WIKIDATA = p.ID_ITEM AND s.ID_PROPERTY = 'P31' AND s.DELETED = 0
JOIN T_WC_WIKIDATA_ITEM_VALUE iv ON iv.ID_STATEMENT = s.ID_STATEMENT
LEFT JOIN T_WC_WIKIDATA_ITEM wi ON wi.ID_WIKIDATA = iv.ID_ITEM
GROUP BY iv.ID_ITEM, wi.LABEL_EN
ORDER BY PARENTS DESC
LIMIT 30;

DROP TEMPORARY TABLE IF EXISTS tmp_p;
