-- TMDB-MOVIE-PREPROCESS-065: preview of step 4c (WIKIPEDIA_IMAGE_PATH for locations). READ-ONLY.
-- Same CASE as f_buildlocationtables(), applied to the served table in a SELECT.
-- Expected: about 10 400 living places with an image (9 883 English + 555 French only).
SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;

SELECT '1. Index on the source table' AS SECTION;
SHOW INDEX FROM T_WC_WIKIPEDIA_PAGE_LANG WHERE Column_name IN ('ID_WIKIDATA', 'LANG');

SELECT '2. Duplicate (ID_WIKIDATA, LANG) among location QIDs (expected 0)' AS SECTION;
SELECT COUNT(*) AS DOUBLONS FROM (
  SELECT p.ID_WIKIDATA, p.LANG FROM T_WC_WIKIPEDIA_PAGE_LANG p
  JOIN T_WC_T2S_LOCATION l ON l.ID_WIKIDATA = p.ID_WIKIDATA
  WHERE p.LANG IN ('en', 'fr') GROUP BY p.ID_WIKIDATA, p.LANG HAVING COUNT(*) > 1) d;

SELECT '3. Living places with an image after 4c' AS SECTION;
SELECT COUNT(*) AS LIEUX,
       SUM(x.IMG IS NOT NULL AND x.IMG <> '') AS AVEC_IMAGE,
       SUM(x.SRC = 'en') AS DEPUIS_EN, SUM(x.SRC = 'fr') AS DEPUIS_FR
FROM (
  SELECT CASE WHEN pen.MAIN_IMAGE_URL IS NULL AND pfr.MAIN_IMAGE_URL IS NULL THEN l.WIKIPEDIA_IMAGE_PATH
              ELSE COALESCE(NULLIF(pen.MAIN_IMAGE_URL, ''), NULLIF(pfr.MAIN_IMAGE_URL, '')) END AS IMG,
         CASE WHEN NULLIF(pen.MAIN_IMAGE_URL, '') IS NOT NULL THEN 'en'
              WHEN NULLIF(pfr.MAIN_IMAGE_URL, '') IS NOT NULL THEN 'fr' END AS SRC
  FROM T_WC_T2S_LOCATION l
  LEFT JOIN T_WC_WIKIPEDIA_PAGE_LANG pen ON pen.ID_WIKIDATA = l.ID_WIKIDATA AND pen.LANG = 'en'
  LEFT JOIN T_WC_WIKIPEDIA_PAGE_LANG pfr ON pfr.ID_WIKIDATA = l.ID_WIKIDATA AND pfr.LANG = 'fr'
  WHERE l.DELETED = 0) x;

SELECT '4. Los Angeles, London, Paris, Tokyo' AS SECTION;
SELECT l.ID_WIKIDATA, l.LOCATION_NAME,
       LEFT(CASE WHEN pen.MAIN_IMAGE_URL IS NULL AND pfr.MAIN_IMAGE_URL IS NULL THEN l.WIKIPEDIA_IMAGE_PATH
                 ELSE COALESCE(NULLIF(pen.MAIN_IMAGE_URL, ''), NULLIF(pfr.MAIN_IMAGE_URL, '')) END, 160) AS IMG
FROM T_WC_T2S_LOCATION l
LEFT JOIN T_WC_WIKIPEDIA_PAGE_LANG pen ON pen.ID_WIKIDATA = l.ID_WIKIDATA AND pen.LANG = 'en'
LEFT JOIN T_WC_WIKIPEDIA_PAGE_LANG pfr ON pfr.ID_WIKIDATA = l.ID_WIKIDATA AND pfr.LANG = 'fr'
WHERE l.ID_WIKIDATA IN ('Q65', 'Q84', 'Q90', 'Q1490');

SELECT '5. Images shared by several places (banner suspects)' AS SECTION;
SELECT LEFT(x.IMG, 140) AS IMG, COUNT(*) AS LIEUX FROM (
  SELECT COALESCE(NULLIF(pen.MAIN_IMAGE_URL, ''), NULLIF(pfr.MAIN_IMAGE_URL, '')) AS IMG
  FROM T_WC_T2S_LOCATION l
  LEFT JOIN T_WC_WIKIPEDIA_PAGE_LANG pen ON pen.ID_WIKIDATA = l.ID_WIKIDATA AND pen.LANG = 'en'
  LEFT JOIN T_WC_WIKIPEDIA_PAGE_LANG pfr ON pfr.ID_WIKIDATA = l.ID_WIKIDATA AND pfr.LANG = 'fr'
  WHERE l.DELETED = 0) x
WHERE x.IMG IS NOT NULL GROUP BY x.IMG HAVING COUNT(*) > 2 ORDER BY LIEUX DESC LIMIT 10;
