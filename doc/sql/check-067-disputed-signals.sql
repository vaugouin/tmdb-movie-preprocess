-- TMDB-MOVIE-PREPROCESS-067: what Wikidata says on the P17 statements of the cross-border
-- places, to turn Philippe's three decisions of 2026-10-21 into a rule:
--   1. a disputed territory (Jerusalem, West Bank, Crimea, Sevastopol) goes under each
--      claimed country instead of none;
--   2. Normandy (Q15878: France, Guernsey, Jersey) stays under France;
--   3. only the P17 parents the database knows (a T_WC_WIKIDATA_ITEM row) count for (b).
-- The question: is there a qualifier (P1310 statement disputed by, P518 applies to part,
-- P5102 nature of statement...) or a P31 (Q15239622 disputed territory) that marks the
-- disputed ones and the partial ones, so the rule needs no list of names.
--
-- Read-only, voie 1. Written 2026-10-21. Same edges as test-067-cross-border-places.sql.

SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;

DROP TEMPORARY TABLE IF EXISTS tmp_s;
CREATE TEMPORARY TABLE tmp_s (
  ID_STATEMENT BIGINT NOT NULL PRIMARY KEY, ID_CHILD VARCHAR(50) NOT NULL, ID_PARENT VARCHAR(50) NOT NULL,
  KEY (ID_CHILD), KEY (ID_PARENT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

INSERT IGNORE INTO tmp_s
SELECT st.ID_STATEMENT, st.ID_WIKIDATA, iv.ID_ITEM
FROM T_WC_WIKIDATA_STATEMENT st
INNER JOIN T_WC_WIKIDATA_ITEM_VALUE iv ON iv.ID_STATEMENT = st.ID_STATEMENT
WHERE st.ID_PROPERTY = 'P17'
  AND st.DELETED = 0
  AND (st.`RANK` IS NULL OR st.`RANK` <> 'deprecated')
  AND (st.`RANK` = 'preferred'
       OR NOT EXISTS (SELECT 1 FROM T_WC_WIKIDATA_STATEMENT p
                      WHERE p.ID_WIKIDATA = st.ID_WIKIDATA AND p.ID_PROPERTY = 'P17'
                        AND p.`RANK` = 'preferred' AND p.DELETED = 0))
  AND iv.ID_ITEM <> st.ID_WIKIDATA
  AND st.ID_WIKIDATA IN (SELECT ID_WIKIDATA FROM T_WC_T2S_LOCATION WHERE DELETED = 0);

-- Parents ended (same classes as the test) or unknown to the database are left out.
DELETE s FROM tmp_s s
WHERE NOT EXISTS (SELECT 1 FROM T_WC_WIKIDATA_ITEM wi WHERE wi.ID_WIKIDATA = s.ID_PARENT)
   OR EXISTS (SELECT 1 FROM T_WC_WIKIDATA_STATEMENT p31
              JOIN T_WC_WIKIDATA_ITEM_VALUE v ON v.ID_STATEMENT = p31.ID_STATEMENT
              WHERE p31.ID_WIKIDATA = s.ID_PARENT AND p31.ID_PROPERTY = 'P31' AND p31.DELETED = 0
                AND (p31.`RANK` IS NULL OR p31.`RANK` <> 'deprecated')
                AND v.ID_ITEM IN ('Q3024240', 'Q11514315', 'Q2577883', 'Q19953632'));

DROP TEMPORARY TABLE IF EXISTS tmp_cross;
CREATE TEMPORARY TABLE tmp_cross (ID_CHILD VARCHAR(50) NOT NULL PRIMARY KEY, N_P17 INT NOT NULL)
  ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
INSERT INTO tmp_cross
SELECT ID_CHILD, COUNT(DISTINCT ID_PARENT) FROM tmp_s GROUP BY ID_CHILD HAVING COUNT(DISTINCT ID_PARENT) >= 2;

SELECT '1. Cross-border living places with known parents only (decision 3)' AS SECTION;

SELECT COUNT(*) AS CROSS_T2S_PLACES FROM tmp_cross;

SELECT '2. Qualifiers on the P17 statements of the cross-border places' AS SECTION;

SELECT q.ID_QUALIFIER_PROPERTY, wp.LABEL_EN, COUNT(DISTINCT s.ID_STATEMENT) AS STATEMENTS, COUNT(DISTINCT s.ID_CHILD) AS PLACES
FROM tmp_s s
JOIN tmp_cross c ON c.ID_CHILD = s.ID_CHILD
JOIN T_WC_WIKIDATA_STATEMENT_QUALIFIER q ON q.ID_STATEMENT = s.ID_STATEMENT AND COALESCE(q.DELETED, 0) = 0
LEFT JOIN T_WC_WIKIDATA_ITEM wp ON wp.ID_WIKIDATA = q.ID_QUALIFIER_PROPERTY
GROUP BY q.ID_QUALIFIER_PROPERTY, wp.LABEL_EN
ORDER BY PLACES DESC;

SELECT '3. Most frequent P31 of the cross-border places' AS SECTION;

SELECT v.ID_ITEM AS P31_CLASS, wi.LABEL_EN, COUNT(DISTINCT c.ID_CHILD) AS PLACES
FROM tmp_cross c
JOIN T_WC_WIKIDATA_STATEMENT p31 ON p31.ID_WIKIDATA = c.ID_CHILD AND p31.ID_PROPERTY = 'P31' AND p31.DELETED = 0
JOIN T_WC_WIKIDATA_ITEM_VALUE v ON v.ID_STATEMENT = p31.ID_STATEMENT
LEFT JOIN T_WC_WIKIDATA_ITEM wi ON wi.ID_WIKIDATA = v.ID_ITEM
GROUP BY v.ID_ITEM, wi.LABEL_EN
ORDER BY PLACES DESC
LIMIT 40;

SELECT '4. Witnesses: each P17 statement with its qualifiers' AS SECTION;

SELECT s.ID_CHILD, l.LOCATION_NAME, s.ID_PARENT, wp.LABEL_EN AS PARENT, st.`RANK`,
       (SELECT GROUP_CONCAT(CONCAT(q.ID_QUALIFIER_PROPERTY, '=', LEFT(COALESCE(q.RAW_VALUE_TEXT, '?'), 40)) ORDER BY q.ID_QUALIFIER_PROPERTY SEPARATOR ' | ')
          FROM T_WC_WIKIDATA_STATEMENT_QUALIFIER q WHERE q.ID_STATEMENT = s.ID_STATEMENT AND COALESCE(q.DELETED, 0) = 0) AS QUALIFIERS
FROM tmp_s s
JOIN T_WC_WIKIDATA_STATEMENT st ON st.ID_STATEMENT = s.ID_STATEMENT
JOIN T_WC_T2S_LOCATION l ON l.ID_WIKIDATA = s.ID_CHILD AND l.DELETED = 0
LEFT JOIN T_WC_WIKIDATA_ITEM wp ON wp.ID_WIKIDATA = s.ID_PARENT
WHERE s.ID_CHILD IN ('Q15878', 'Q1218', 'Q7204', 'Q407199', 'Q23792', 'Q7835', 'Q7525', 'Q133356', 'Q11946',
                     'Q93332', 'Q4918', 'Q7204', 'Q4917', 'Q1286', 'Q1781', 'Q47588', 'Q22890')
ORDER BY l.LOCATION_NAME, wp.LABEL_EN;

SELECT '5. All cross-border living places with their P31 (to sort disputed from spread)' AS SECTION;

SELECT l.ID_LOCATION, l.ID_WIKIDATA, l.LOCATION_NAME, l.LOCATION_TYPE, c.N_P17, l.MOVIE_COUNT + l.SERIE_COUNT AS WORKS,
       (SELECT GROUP_CONCAT(DISTINCT COALESCE(wi.LABEL_EN, v.ID_ITEM) ORDER BY 1 SEPARATOR ', ')
          FROM T_WC_WIKIDATA_STATEMENT p31 JOIN T_WC_WIKIDATA_ITEM_VALUE v ON v.ID_STATEMENT = p31.ID_STATEMENT
          LEFT JOIN T_WC_WIKIDATA_ITEM wi ON wi.ID_WIKIDATA = v.ID_ITEM
         WHERE p31.ID_WIKIDATA = c.ID_CHILD AND p31.ID_PROPERTY = 'P31' AND p31.DELETED = 0) AS P31,
       (SELECT GROUP_CONCAT(DISTINCT CONCAT(COALESCE(wp.LABEL_EN, s.ID_PARENT),
                 IF(EXISTS (SELECT 1 FROM T_WC_WIKIDATA_STATEMENT_QUALIFIER q WHERE q.ID_STATEMENT = s.ID_STATEMENT AND COALESCE(q.DELETED, 0) = 0),
                    CONCAT(' [', (SELECT GROUP_CONCAT(DISTINCT q.ID_QUALIFIER_PROPERTY SEPARATOR ' ') FROM T_WC_WIKIDATA_STATEMENT_QUALIFIER q
                                  WHERE q.ID_STATEMENT = s.ID_STATEMENT AND COALESCE(q.DELETED, 0) = 0), ']'), ''))
               ORDER BY 1 SEPARATOR ', ')
          FROM tmp_s s LEFT JOIN T_WC_WIKIDATA_ITEM wp ON wp.ID_WIKIDATA = s.ID_PARENT
         WHERE s.ID_CHILD = c.ID_CHILD) AS P17
FROM tmp_cross c JOIN T_WC_T2S_LOCATION l ON l.ID_WIKIDATA = c.ID_CHILD AND l.DELETED = 0
ORDER BY WORKS DESC;

DROP TEMPORARY TABLE IF EXISTS tmp_cross;
DROP TEMPORARY TABLE IF EXISTS tmp_s;
