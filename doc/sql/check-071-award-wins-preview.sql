SELECT '=== E1. Katharine Hepburn (Q56016): her win rows ===' AS section;

SELECT a.AWARD_NAME, q.YEAR_MIN AS AWARD_YEAR, q.WORK_MIN AS ID_WORK_WIKIDATA, m.TITLE AS MOVIE_FOR, q.CEREMONY_MIN AS ID_CEREMONY
FROM tmp_071_win w
