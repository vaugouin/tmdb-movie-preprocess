-- TMDB-MOVIE-PREPROCESS-064: acceptance after the first run of process 72 in 1.1.20.
--
-- Read-only (SELECT only), voie 1. Written 2026-10-21. Sibling of test-064-location-labels.sql,
-- which measured the expressions before the fix (expected: 1 place without a name, 0 without
-- a French name, 10 175 French descriptions, about 12 295 rated places). Section 1 says
-- whether the run happened (OVERVIEW_FR column, last TIM_UPDATED); the sections after it read
-- the column and fail if it is not there yet.
-- Section 5 also checks a doubt raised by the acceptance of FASTAPI-TEXT2SQL-335: the series
-- list of France (contained scope) shows a series linked to "Appalaches".

SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;

SELECT '1. Did process 72 run with 1.1.20?' AS SECTION;

SELECT COUNT(*) AS OVERVIEW_FR_COLUMN
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'T_WC_T2S_LOCATION' AND COLUMN_NAME = 'OVERVIEW_FR';

SELECT MAX(TIM_UPDATED) AS LAST_UPDATED, COUNT(*) AS LIVING FROM T_WC_T2S_LOCATION WHERE DELETED = 0;

SELECT '2. Hierarchy-based sheets: the counts of the France sheet (ID 126)' AS SECTION;

SELECT j.LOCATION_ROLE, COUNT(DISTINCT j.ID_MOVIE) AS MOVIES_CONTAINED
FROM T_WC_T2S_LOCATION_ANCESTOR a
JOIN T_WC_T2S_MOVIE_LOCATION j ON j.ID_LOCATION = a.ID_LOCATION AND COALESCE(j.DELETED, 0) = 0
JOIN T_WC_T2S_MOVIE m ON m.ID_MOVIE = j.ID_MOVIE AND COALESCE(m.DELETED, 0) = 0
WHERE a.ID_ANCESTOR = 126
GROUP BY j.LOCATION_ROLE;

SELECT '3. Labels' AS SECTION;

SELECT COUNT(*) AS LIVING,
       SUM(LOCATION_NAME IS NULL OR LOCATION_NAME = '') AS NO_NAME,
       SUM(LOCATION_NAME_FR IS NULL OR LOCATION_NAME_FR = '') AS NO_NAME_FR,
       SUM(LOCATION_NAME_FR = LOCATION_NAME) AS FR_EQUALS_EN,
       SUM(IMDB_RATING_WEIGHTED IS NOT NULL) AS RATED,
       SUM(POPULARITY IS NOT NULL) AS WITH_POPULARITY,
       SUM(MOVIE_COUNT = 0 AND SERIE_COUNT > 0 AND IMDB_RATING_WEIGHTED IS NULL) AS SERIES_ONLY_NO_RATING
FROM T_WC_T2S_LOCATION WHERE DELETED = 0;

SELECT ID_LOCATION, ID_WIKIDATA, LOCATION_NAME, LOCATION_NAME_FR, MOVIE_COUNT, SERIE_COUNT, EPISODE_COUNT
FROM T_WC_T2S_LOCATION
WHERE DELETED = 0 AND (LOCATION_NAME IS NULL OR LOCATION_NAME = '' OR LOCATION_NAME_FR IS NULL OR LOCATION_NAME_FR = '');

SELECT '4. French descriptions' AS SECTION;

SELECT SUM(OVERVIEW_FR IS NOT NULL AND OVERVIEW_FR <> '') AS WITH_OVERVIEW_FR,
       SUM(OVERVIEW IS NOT NULL AND OVERVIEW <> '') AS WITH_OVERVIEW
FROM T_WC_T2S_LOCATION WHERE DELETED = 0;

SELECT ID_LOCATION, ID_WIKIDATA, LOCATION_NAME, LOCATION_NAME_FR, OVERVIEW_FR,
       ROUND(IMDB_RATING_WEIGHTED, 3) AS RW, ROUND(POPULARITY, 3) AS P, MOVIE_COUNT, SERIE_COUNT
FROM T_WC_T2S_LOCATION
WHERE ID_WIKIDATA IN ('Q90', 'Q84', 'Q142', 'Q24639', 'Q2669', 'Q216344');

SELECT '5. Doubt: places named Appalaches and their path up to France' AS SECTION;

SELECT l.ID_LOCATION, l.ID_WIKIDATA, l.LOCATION_NAME, l.LOCATION_NAME_FR, l.LOCATION_TYPE
FROM T_WC_T2S_LOCATION l
WHERE l.DELETED = 0 AND (l.LOCATION_NAME_FR LIKE 'Appalach%' OR l.LOCATION_NAME LIKE 'Appalach%');

SELECT a.ID_LOCATION, a.ID_ANCESTOR, anc.LOCATION_NAME AS ANCESTOR, anc.ID_WIKIDATA, a.DEPTH
FROM T_WC_T2S_LOCATION_ANCESTOR a
JOIN T_WC_T2S_LOCATION l ON l.ID_LOCATION = a.ID_LOCATION
JOIN T_WC_T2S_LOCATION anc ON anc.ID_LOCATION = a.ID_ANCESTOR
WHERE l.DELETED = 0 AND (l.LOCATION_NAME_FR LIKE 'Appalach%' OR l.LOCATION_NAME LIKE 'Appalach%')
ORDER BY a.ID_LOCATION, a.DEPTH;

SELECT '5b. Contained places of France at depth 1, by number of linked movies' AS SECTION;

SELECT l.ID_LOCATION, l.ID_WIKIDATA, l.LOCATION_NAME, l.LOCATION_TYPE, l.MOVIE_COUNT, l.SERIE_COUNT
FROM T_WC_T2S_LOCATION_ANCESTOR a
JOIN T_WC_T2S_LOCATION l ON l.ID_LOCATION = a.ID_LOCATION AND l.DELETED = 0
WHERE a.ID_ANCESTOR = 126 AND a.DEPTH = 1
ORDER BY l.MOVIE_COUNT + l.SERIE_COUNT DESC
LIMIT 40;
