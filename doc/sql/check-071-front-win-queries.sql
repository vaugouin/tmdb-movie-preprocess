-- TMDB-MOVIE-PREPROCESS-071, display of the wins: the queries the web front (award lines of the
-- person, movie and series pages, lists of the award page) and the API helper
-- _attach_award_wins() send, run once on the live base before the front is deployed.
-- Read-only. Expected: Hepburn (6598) four rows on award 269 with 1934, 1968, 1969, 1982 and
-- their films; A Prophet (21575) with 2010 on award 25677; no SQL error.

SELECT '=== 1. person page: the wins of Katharine Hepburn (6598), with the work ===' AS section;
SELECT T_WC_T2S_AWARD.ID_AWARD, T_WC_T2S_AWARD.AWARD_NAME, T_WC_T2S_AWARD.AWARD_NAME_FR, T_WC_T2S_PERSON_AWARD.AWARD_YEAR, T_WC_T2S_PERSON_AWARD.ID_MOVIE_FOR, AWARDMOVIE.MOVIE_TITLE, AWARDMOVIE.MOVIE_TITLE_FR, T_WC_T2S_PERSON_AWARD.ID_SERIE_FOR, AWARDSERIE.SERIE_TITLE, AWARDSERIE.SERIE_TITLE_FR
FROM T_WC_T2S_PERSON_AWARD
INNER JOIN T_WC_T2S_AWARD ON T_WC_T2S_PERSON_AWARD.ID_AWARD = T_WC_T2S_AWARD.ID_AWARD
LEFT JOIN T_WC_T2S_MOVIE AWARDMOVIE ON AWARDMOVIE.ID_MOVIE = T_WC_T2S_PERSON_AWARD.ID_MOVIE_FOR
LEFT JOIN T_WC_T2S_SERIE AWARDSERIE ON AWARDSERIE.ID_SERIE = T_WC_T2S_PERSON_AWARD.ID_SERIE_FOR
WHERE T_WC_T2S_PERSON_AWARD.ID_PERSON = 6598 AND T_WC_T2S_PERSON_AWARD.DELETED = 0 AND T_WC_T2S_AWARD.DELETED = 0
ORDER BY T_WC_T2S_PERSON_AWARD.DISPLAY_ORDER, T_WC_T2S_AWARD.AWARD_NAME, T_WC_T2S_AWARD.ID_AWARD, T_WC_T2S_PERSON_AWARD.AWARD_YEAR;

SELECT '=== 2. movie page: the wins of A Prophet (21575) ===' AS section;
SELECT T_WC_T2S_AWARD.ID_AWARD, T_WC_T2S_AWARD.AWARD_NAME, T_WC_T2S_AWARD.AWARD_NAME_FR, T_WC_T2S_MOVIE_AWARD.AWARD_YEAR
FROM T_WC_T2S_MOVIE_AWARD
INNER JOIN T_WC_T2S_AWARD ON T_WC_T2S_MOVIE_AWARD.ID_AWARD = T_WC_T2S_AWARD.ID_AWARD
WHERE T_WC_T2S_MOVIE_AWARD.ID_MOVIE = 21575 AND T_WC_T2S_MOVIE_AWARD.DELETED = 0 AND T_WC_T2S_AWARD.DELETED = 0
ORDER BY T_WC_T2S_MOVIE_AWARD.DISPLAY_ORDER, T_WC_T2S_AWARD.AWARD_NAME, T_WC_T2S_AWARD.ID_AWARD, T_WC_T2S_MOVIE_AWARD.AWARD_YEAR;

SELECT '=== 3. series page: the wins of series 688 ===' AS section;
SELECT T_WC_T2S_AWARD.ID_AWARD, T_WC_T2S_AWARD.AWARD_NAME, T_WC_T2S_AWARD.AWARD_NAME_FR, T_WC_T2S_SERIE_AWARD.AWARD_YEAR
FROM T_WC_T2S_SERIE_AWARD
INNER JOIN T_WC_T2S_AWARD ON T_WC_T2S_SERIE_AWARD.ID_AWARD = T_WC_T2S_AWARD.ID_AWARD
WHERE T_WC_T2S_SERIE_AWARD.ID_SERIE = 688 AND T_WC_T2S_SERIE_AWARD.DELETED = 0 AND T_WC_T2S_AWARD.DELETED = 0
ORDER BY T_WC_T2S_SERIE_AWARD.DISPLAY_ORDER, T_WC_T2S_AWARD.AWARD_NAME, T_WC_T2S_AWARD.ID_AWARD, T_WC_T2S_SERIE_AWARD.AWARD_YEAR
LIMIT 15;

SELECT '=== 4. award page, movies: the years of Cesar Award for Best Film (25677), 2008 to 2011 ===' AS section;
SELECT ID_MOVIE, AWARD_YEAR FROM T_WC_T2S_MOVIE_AWARD WHERE ID_AWARD = 25677 AND AWARD_YEAR BETWEEN 2008 AND 2011 ORDER BY AWARD_YEAR;

SELECT '=== 5. award page, series: rows of the award of series 688 with the most series wins ===' AS section;
SELECT ID_SERIE, AWARD_YEAR FROM T_WC_T2S_SERIE_AWARD WHERE ID_AWARD = (SELECT ID_AWARD FROM T_WC_T2S_SERIE_AWARD WHERE ID_SERIE = 688 GROUP BY ID_AWARD ORDER BY COUNT(*) DESC, ID_AWARD LIMIT 1) LIMIT 10;

SELECT '=== 6. award page, persons: Academy Award for Best Actress (269), wins of 1980 to 1984 with the work ===' AS section;
SELECT W.ID_PERSON, W.AWARD_YEAR, W.ID_MOVIE_FOR, M.MOVIE_TITLE, M.MOVIE_TITLE_FR, W.ID_SERIE_FOR, S.SERIE_TITLE, S.SERIE_TITLE_FR
FROM T_WC_T2S_PERSON_AWARD W
LEFT JOIN T_WC_T2S_MOVIE M ON M.ID_MOVIE = W.ID_MOVIE_FOR
LEFT JOIN T_WC_T2S_SERIE S ON S.ID_SERIE = W.ID_SERIE_FOR
WHERE W.ID_AWARD = 269 AND W.AWARD_YEAR BETWEEN 1980 AND 1984
ORDER BY W.AWARD_YEAR;

SELECT '=== 7. API helper: the wins behind the awards list of a person (6598, awards 269 and 500) ===' AS section;
SELECT w.ID_AWARD AS _WIN_KEY, w.AWARD_YEAR, w.ID_MOVIE_FOR, m.MOVIE_TITLE, m.MOVIE_TITLE_FR, w.ID_SERIE_FOR, s.SERIE_TITLE, s.SERIE_TITLE_FR FROM T_WC_T2S_PERSON_AWARD w LEFT JOIN T_WC_T2S_MOVIE m ON m.ID_MOVIE = w.ID_MOVIE_FOR LEFT JOIN T_WC_T2S_SERIE s ON s.ID_SERIE = w.ID_SERIE_FOR WHERE w.ID_PERSON = 6598 AND w.ID_AWARD IN (269, 500) ORDER BY w.AWARD_YEAR IS NULL, w.AWARD_YEAR ASC, w.ID_ROW ASC;

SELECT '=== 8. size of the award page queries: wins of the award with the most person wins ===' AS section;
SELECT ID_AWARD, COUNT(*) AS WIN_ROWS, COUNT(DISTINCT ID_PERSON) AS PERSONS FROM T_WC_T2S_PERSON_AWARD GROUP BY ID_AWARD ORDER BY WIN_ROWS DESC LIMIT 3;
