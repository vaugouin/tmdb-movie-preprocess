-- TMDB-MOVIE-PREPROCESS-069: read-only preview of process 52 (movie and series title aliases).
-- Runs the SELECT of every INSERT of f_buildtitlealiastables() without writing anything:
-- forms per source and table, before the unique key (so a few duplicates across sources are
-- still counted), then samples. Checks the SQL (JSON_TABLE, collation) on the live base
-- before the first nightly run. P1476 counts stay at 0 until wikidata-crawler 1.1.14
-- (WIKIDATA-CRAWLER-031) has loaded a dump.
-- Generated from tmdb_preprocess_helpers.f_titlealiasinsertsql on 2026-11-03.
-- Run (SELECT only):
--   ssh vps-agent run tmdb-movie-preprocess/doc/sql/check-069-title-alias-preview.sql
-- or ~/docker/tools/runsqlvaugouindb.sh ~/docker/tmdb-movie-preprocess/doc/sql/check-069-title-alias-preview.sql

SELECT 'T_WC_T2S_MOVIE_TITLE_ALIAS title' AS STEP, COUNT(*) AS FORMS FROM (
SELECT x.ID_MOVIE, x.TITLE, x.LANG_CODE
FROM (
  SELECT m.ID_MOVIE, CONVERT(LEFT(TRIM(sv.VALUE_STRING), 500) USING utf8mb4) COLLATE utf8mb4_unicode_ci AS TITLE, sv.LANG_CODE
  FROM T_WC_T2S_MOVIE m
  JOIN T_WC_WIKIDATA_STATEMENT st ON st.ID_WIKIDATA = m.ID_WIKIDATA AND st.ID_PROPERTY = 'P1476'
       AND COALESCE(st.DELETED, 0) = 0 AND COALESCE(st.`RANK`, 'normal') <> 'deprecated'
  JOIN T_WC_WIKIDATA_STRING_VALUE sv ON sv.ID_STATEMENT = st.ID_STATEMENT
  WHERE COALESCE(m.DELETED, 0) = 0 AND m.ID_WIKIDATA IS NOT NULL AND m.ID_WIKIDATA <> ''
) x
JOIN T_WC_T2S_MOVIE m ON m.ID_MOVIE = x.ID_MOVIE
WHERE x.TITLE IS NOT NULL AND x.TITLE <> '' AND x.TITLE <> COALESCE(m.MOVIE_TITLE, '') AND x.TITLE <> COALESCE(m.MOVIE_TITLE_FR, '') AND x.TITLE <> COALESCE(m.ORIGINAL_TITLE, '')
) q;

