SELECT m.ORIGINAL_TITLE AS TMDB_ORIGINAL_TITLE, x.ID_SERIE, x.TITLE, x.LANG_CODE
FROM (
  SELECT m.ID_SERIE, CONVERT(LEFT(TRIM(JSON_UNQUOTE(JSON_EXTRACT(w.LABELS_JSON, '$.mul'))), 500) USING utf8mb4) COLLATE utf8mb4_unicode_ci AS TITLE,
         'mul' AS LANG_CODE
  FROM T_WC_T2S_SERIE m
  JOIN T_WC_WIKIDATA_SERIE w ON w.ID_WIKIDATA = m.ID_WIKIDATA AND COALESCE(w.DELETED, 0) = 0
  WHERE COALESCE(m.DELETED, 0) = 0 AND m.ID_WIKIDATA IS NOT NULL AND m.ID_WIKIDATA <> ''
    AND JSON_EXTRACT(w.LABELS_JSON, '$.mul') IS NOT NULL
) x
JOIN T_WC_T2S_SERIE m ON m.ID_SERIE = x.ID_SERIE
WHERE x.TITLE IS NOT NULL AND x.TITLE <> '' AND x.TITLE <> COALESCE(m.SERIE_TITLE, '') AND x.TITLE <> COALESCE(m.SERIE_TITLE_FR, '') AND x.TITLE <> COALESCE(m.ORIGINAL_TITLE, '')
ORDER BY m.POPULARITY DESC
LIMIT 15;
