-- T_WC_WIKIPEDIA_PAGE_LANG.MAIN_IMAGE_URL is varchar(1000), WIKIPEDIA_IMAGE_PATH varchar(500).
-- How many location image URLs are longer than 500, and what do they look like?
SELECT p.LANG,
       COUNT(*) AS URLS,
       SUM(CHAR_LENGTH(p.MAIN_IMAGE_URL) > 500) AS OVER_500,
       MAX(CHAR_LENGTH(p.MAIN_IMAGE_URL)) AS MAX_LEN
FROM T_WC_T2S_LOCATION loc
JOIN T_WC_WIKIPEDIA_PAGE_LANG p ON p.ID_WIKIDATA = loc.ID_WIKIDATA AND p.LANG IN ('en', 'fr')
WHERE p.MAIN_IMAGE_URL IS NOT NULL AND p.MAIN_IMAGE_URL <> ''
GROUP BY p.LANG;

SELECT loc.ID_WIKIDATA, loc.LOCATION_NAME, p.LANG, CHAR_LENGTH(p.MAIN_IMAGE_URL) AS LEN,
       LEFT(p.MAIN_IMAGE_URL, 160) AS URL_START
FROM T_WC_T2S_LOCATION loc
JOIN T_WC_WIKIPEDIA_PAGE_LANG p ON p.ID_WIKIDATA = loc.ID_WIKIDATA AND p.LANG IN ('en', 'fr')
WHERE CHAR_LENGTH(p.MAIN_IMAGE_URL) > 500
ORDER BY LEN DESC
LIMIT 20;
