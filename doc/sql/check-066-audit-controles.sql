-- 01. Etat des declarations, y compris celles que le SELECT initial exclut.
WITH works AS (
 SELECT 'movie' AS ITEM_TYPE, ID_MOVIE AS ID_ITEM, ID_WIKIDATA FROM T_WC_T2S_MOVIE WHERE COALESCE(DELETED,0)=0
 UNION ALL
 SELECT 'serie', ID_SERIE, ID_WIKIDATA FROM T_WC_T2S_SERIE WHERE COALESCE(DELETED,0)=0
), scope AS (
 SELECT s.* FROM T_WC_WIKIDATA_STATEMENT s
 WHERE s.ID_PROPERTY IN ('P2130','P2142')
 AND EXISTS (SELECT 1 FROM works w WHERE w.ID_WIKIDATA=s.ID_WIKIDATA)
), eligible AS (
 SELECT s.* FROM scope s WHERE COALESCE(s.DELETED,0)=0
 AND (s.`RANK` IS NULL OR s.`RANK`<>'deprecated') AND s.VALUE_TYPE='quantity'
)
SELECT s.ID_PROPERTY,s.`RANK`,s.DELETED,s.VALUE_TYPE,s.IS_VALID,
 COUNT(*) AS N, SUM(q.ID_STATEMENT IS NULL) AS NO_QUANTITY,
 SUM(q.ID_STATEMENT IS NOT NULL AND q.AMOUNT IS NULL) AS NULL_AMOUNT
FROM scope s LEFT JOIN T_WC_WIKIDATA_QUANTITY_VALUE q ON q.ID_STATEMENT=s.ID_STATEMENT
GROUP BY s.ID_PROPERTY,s.`RANK`,s.DELETED,s.VALUE_TYPE,s.IS_VALID;

