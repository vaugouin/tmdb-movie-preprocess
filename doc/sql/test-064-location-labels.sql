-- TMDB-MOVIE-PREPROCESS-064: labels and descriptions of the places, measured before the fix.
--
-- Read-only (SELECT only), voie 1. Written 2026-10-19.
-- Sibling of archive/test-014-location-type-errors.sql (the 150 places without a label of
-- 2026-09-14, never re-measured since the 'mul' fallback of WIKIDATA-CRAWLER-026).
--
--   1. Living places with no LOCATION_NAME, no LOCATION_NAME_FR, today.
--   2. Where a French label would come from with the new fallback: 'fr', then 'mul', then the
--      English LOCATION_NAME.
--   3. How many places have a French description in Wikidata (the future OVERVIEW_FR).
--   4. The aggregates: places whose rating or popularity would change once series count.

SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;

SELECT '1. Living places, labels today' AS SECTION;

SELECT COUNT(*) AS LIVING,
       SUM(LOCATION_NAME IS NULL OR LOCATION_NAME = '') AS NO_NAME,
       SUM(LOCATION_NAME_FR IS NULL OR LOCATION_NAME_FR = '') AS NO_NAME_FR,
       SUM(LOCATION_NAME_FR = LOCATION_NAME) AS FR_EQUALS_EN,
       SUM(OVERVIEW IS NULL OR OVERVIEW = '') AS NO_OVERVIEW
FROM T_WC_T2S_LOCATION WHERE DELETED = 0;

SELECT '1b. Living places with no LOCATION_NAME (sample)' AS SECTION;

SELECT l.ID_LOCATION, l.ID_WIKIDATA, l.LOCATION_NAME_FR, l.LOCATION_TYPE, l.MOVIE_COUNT, l.SERIE_COUNT, l.EPISODE_COUNT,
       LEFT(wi.LABELS_JSON, 120) AS LABELS
FROM T_WC_T2S_LOCATION l
LEFT JOIN T_WC_WIKIDATA_ITEM wi ON wi.ID_WIKIDATA = l.ID_WIKIDATA
WHERE l.DELETED = 0 AND (l.LOCATION_NAME IS NULL OR l.LOCATION_NAME = '')
ORDER BY l.MOVIE_COUNT + l.SERIE_COUNT DESC
LIMIT 20;

SELECT '2. Source of the French label with the new fallback' AS SECTION;

SELECT SUM(JSON_UNQUOTE(JSON_EXTRACT(wi.LABELS_JSON, '$.fr')) IS NOT NULL) AS FROM_FR,
       SUM(JSON_UNQUOTE(JSON_EXTRACT(wi.LABELS_JSON, '$.fr')) IS NULL
           AND JSON_UNQUOTE(JSON_EXTRACT(wi.LABELS_JSON, '$.mul')) IS NOT NULL) AS FROM_MUL,
       SUM(JSON_UNQUOTE(JSON_EXTRACT(wi.LABELS_JSON, '$.fr')) IS NULL
           AND JSON_UNQUOTE(JSON_EXTRACT(wi.LABELS_JSON, '$.mul')) IS NULL
           AND l.LOCATION_NAME IS NOT NULL AND l.LOCATION_NAME <> '') AS FROM_EN,
       SUM(JSON_UNQUOTE(JSON_EXTRACT(wi.LABELS_JSON, '$.fr')) IS NULL
           AND JSON_UNQUOTE(JSON_EXTRACT(wi.LABELS_JSON, '$.mul')) IS NULL
           AND (l.LOCATION_NAME IS NULL OR l.LOCATION_NAME = '')) AS STILL_NONE,
       SUM(wi.ID_WIKIDATA IS NULL) AS NO_WIKIDATA_ROW
FROM T_WC_T2S_LOCATION l
LEFT JOIN T_WC_WIKIDATA_ITEM wi ON wi.ID_WIKIDATA = l.ID_WIKIDATA
WHERE l.DELETED = 0;

SELECT '2b. Places that gain a French label from mul or English (best known first)' AS SECTION;

SELECT l.ID_LOCATION, l.LOCATION_NAME, JSON_UNQUOTE(JSON_EXTRACT(wi.LABELS_JSON, '$.mul')) AS MUL,
       l.LOCATION_TYPE, l.MOVIE_COUNT, l.SERIE_COUNT
FROM T_WC_T2S_LOCATION l
LEFT JOIN T_WC_WIKIDATA_ITEM wi ON wi.ID_WIKIDATA = l.ID_WIKIDATA
WHERE l.DELETED = 0 AND JSON_UNQUOTE(JSON_EXTRACT(wi.LABELS_JSON, '$.fr')) IS NULL
ORDER BY l.MOVIE_COUNT + l.SERIE_COUNT DESC
LIMIT 15;

SELECT '2c. LOCATION_NAME fallback for the places with no English label: en-gb / en-us, fr, mul, then any language' AS SECTION;

SELECT SUM(COALESCE(JSON_UNQUOTE(JSON_EXTRACT(wi.LABELS_JSON, '$."en-gb"')), JSON_UNQUOTE(JSON_EXTRACT(wi.LABELS_JSON, '$."en-us"'))) IS NOT NULL) AS FROM_EN_VARIANT,
       SUM(COALESCE(JSON_UNQUOTE(JSON_EXTRACT(wi.LABELS_JSON, '$."en-gb"')), JSON_UNQUOTE(JSON_EXTRACT(wi.LABELS_JSON, '$."en-us"'))) IS NULL
           AND JSON_UNQUOTE(JSON_EXTRACT(wi.LABELS_JSON, '$.fr')) IS NOT NULL) AS FROM_FR,
       SUM(COALESCE(JSON_UNQUOTE(JSON_EXTRACT(wi.LABELS_JSON, '$."en-gb"')), JSON_UNQUOTE(JSON_EXTRACT(wi.LABELS_JSON, '$."en-us"')),
                    JSON_UNQUOTE(JSON_EXTRACT(wi.LABELS_JSON, '$.fr'))) IS NULL
           AND JSON_UNQUOTE(JSON_EXTRACT(JSON_EXTRACT(wi.LABELS_JSON, '$.*'), '$[0]')) IS NOT NULL) AS FROM_ANY_LANGUAGE,
       SUM(JSON_UNQUOTE(JSON_EXTRACT(JSON_EXTRACT(wi.LABELS_JSON, '$.*'), '$[0]')) IS NULL) AS NO_LABEL_AT_ALL
FROM T_WC_T2S_LOCATION l
LEFT JOIN T_WC_WIKIDATA_ITEM wi ON wi.ID_WIKIDATA = l.ID_WIKIDATA
WHERE l.DELETED = 0 AND (l.LOCATION_NAME IS NULL OR l.LOCATION_NAME = '');

SELECT '2d. The expression process 72 will use, on the first ten such places' AS SECTION;

SELECT l.ID_LOCATION, l.ID_WIKIDATA,
       COALESCE(JSON_UNQUOTE(JSON_EXTRACT(wi.LABELS_JSON, '$.en')), NULLIF(wi.LABEL_EN, ''),
                JSON_UNQUOTE(JSON_EXTRACT(wi.LABELS_JSON, '$."en-gb"')), JSON_UNQUOTE(JSON_EXTRACT(wi.LABELS_JSON, '$."en-us"')),
                JSON_UNQUOTE(JSON_EXTRACT(wi.LABELS_JSON, '$.fr')),
                JSON_UNQUOTE(JSON_EXTRACT(JSON_EXTRACT(wi.LABELS_JSON, '$.*'), '$[0]'))) AS NEW_NAME
FROM T_WC_T2S_LOCATION l
LEFT JOIN T_WC_WIKIDATA_ITEM wi ON wi.ID_WIKIDATA = l.ID_WIKIDATA
WHERE l.DELETED = 0 AND (l.LOCATION_NAME IS NULL OR l.LOCATION_NAME = '')
ORDER BY l.MOVIE_COUNT + l.SERIE_COUNT DESC
LIMIT 10;

SELECT '3. French descriptions available (future OVERVIEW_FR)' AS SECTION;

SELECT SUM(JSON_UNQUOTE(JSON_EXTRACT(wi.DESCRIPTIONS_JSON, '$.fr')) IS NOT NULL) AS WITH_FR_DESCRIPTION,
       SUM(JSON_UNQUOTE(JSON_EXTRACT(wi.DESCRIPTIONS_JSON, '$.fr')) IS NULL) AS WITHOUT_FR_DESCRIPTION,
       MAX(CHAR_LENGTH(JSON_UNQUOTE(JSON_EXTRACT(wi.DESCRIPTIONS_JSON, '$.fr')))) AS LONGEST
FROM T_WC_T2S_LOCATION l
LEFT JOIN T_WC_WIKIDATA_ITEM wi ON wi.ID_WIKIDATA = l.ID_WIKIDATA
WHERE l.DELETED = 0;

SELECT '3b. Examples' AS SECTION;

SELECT l.ID_LOCATION, l.LOCATION_NAME, l.OVERVIEW,
       JSON_UNQUOTE(JSON_EXTRACT(wi.DESCRIPTIONS_JSON, '$.fr')) AS OVERVIEW_FR
FROM T_WC_T2S_LOCATION l
LEFT JOIN T_WC_WIKIDATA_ITEM wi ON wi.ID_WIKIDATA = l.ID_WIKIDATA
WHERE l.ID_WIKIDATA IN ('Q90', 'Q84', 'Q405', 'Q216344');

SELECT '4. Places linked to series only (rating NULL today, set once series count)' AS SECTION;

SELECT SUM(MOVIE_COUNT = 0 AND SERIE_COUNT > 0) AS SERIES_ONLY,
       SUM(MOVIE_COUNT = 0 AND SERIE_COUNT > 0 AND IMDB_RATING IS NULL) AS SERIES_ONLY_NO_RATING,
       SUM(MOVIE_COUNT > 0 AND SERIE_COUNT > 0) AS MOVIES_AND_SERIES
FROM T_WC_T2S_LOCATION WHERE DELETED = 0;

SELECT '4b. Pooled averages for a few places (movies and series, one vote per work: UNION drops the second role of a work)' AS SECTION;

SELECT l.ID_LOCATION, l.LOCATION_NAME, l.IMDB_RATING_WEIGHTED AS TODAY_WEIGHTED, l.POPULARITY AS TODAY_POP,
       (SELECT AVG(w.R) FROM (
           SELECT 'm' AS K, m.ID_MOVIE AS ID_WORK, m.IMDB_RATING_WEIGHTED AS R, ml.ID_LOCATION FROM T_WC_T2S_MOVIE_LOCATION ml
             JOIN T_WC_T2S_MOVIE m ON m.ID_MOVIE = ml.ID_MOVIE WHERE m.IMDB_RATING_WEIGHTED > 0
           UNION
           SELECT 's', s.ID_SERIE, s.IMDB_RATING_WEIGHTED, sl.ID_LOCATION FROM T_WC_T2S_SERIE_LOCATION sl
             JOIN T_WC_T2S_SERIE s ON s.ID_SERIE = sl.ID_SERIE WHERE s.IMDB_RATING_WEIGHTED > 0) w
         WHERE w.ID_LOCATION = l.ID_LOCATION) AS POOLED_WEIGHTED,
       l.MOVIE_COUNT, l.SERIE_COUNT
FROM T_WC_T2S_LOCATION l
WHERE l.ID_WIKIDATA IN ('Q90', 'Q84', 'Q24639', 'Q2669');
