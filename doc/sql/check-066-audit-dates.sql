-- Bornes de granularite, PAS une duree de validite affirmee.
-- Les valeurs hors contrat restent brutes avec bornes NULL.
WITH works AS (
 SELECT 'movie' AS ITEM_TYPE, ID_MOVIE AS ID_ITEM, ID_WIKIDATA FROM T_WC_T2S_MOVIE WHERE COALESCE(DELETED,0)=0
 UNION ALL
 SELECT 'serie', ID_SERIE, ID_WIKIDATA FROM T_WC_T2S_SERIE WHERE COALESCE(DELETED,0)=0
), scope AS (
 SELECT s.* FROM T_WC_WIKIDATA_STATEMENT s
 WHERE s.ID_PROPERTY IN ('P2130','P2142')
 AND EXISTS (SELECT 1 FROM works w WHERE w.ID_WIKIDATA=s.ID_WIKIDATA)
), eligible AS (
 SELECT s.* FROM scope s WHERE COALESCE(s.DELETED,0)=0
 AND (s.`RANK` IS NULL OR s.`RANK`<>'deprecated') AND s.VALUE_TYPE='quantity'
), times AS (
 SELECT sq.ID_STATEMENT,sq.ID_QUALIFIER_PROPERTY,tv.*,
 CASE WHEN tv.YEAR_VALUE BETWEEN 1000 AND 9999
 AND SUBSTRING_INDEX(tv.CALENDAR_MODEL,'/',-1)='Q1985727'
 AND COALESCE(tv.TIMEZONE_OFFSET,0)=0 AND tv.TIME_PRECISION IN (9,10,11)
 AND (tv.TIME_PRECISION=9 OR tv.MONTH_VALUE BETWEEN 1 AND 12)
 THEN MAKEDATE(tv.YEAR_VALUE,1) + INTERVAL (CASE WHEN tv.TIME_PRECISION=9 THEN 0 ELSE tv.MONTH_VALUE-1 END) MONTH
 END AS MONTH_ANCHOR
 FROM eligible s JOIN T_WC_WIKIDATA_STATEMENT_QUALIFIER sq ON sq.ID_STATEMENT=s.ID_STATEMENT
 JOIN T_WC_WIKIDATA_QUALIFIER_TIME_VALUE tv ON tv.ID_STATEMENT_QUALIFIER=sq.ID_STATEMENT_QUALIFIER
 WHERE COALESCE(sq.DELETED,0)=0 AND sq.VALUE_TYPE='time'
 AND sq.ID_QUALIFIER_PROPERTY IN ('P585','P580','P582')
), converted AS (
 SELECT times.*,
 CASE WHEN TIME_PRECISION IN (9,10) THEN MONTH_ANCHOR
 WHEN TIME_PRECISION=11 AND DAY_VALUE BETWEEN 1 AND DAY(LAST_DAY(MONTH_ANCHOR))
 THEN MONTH_ANCHOR + INTERVAL (DAY_VALUE-1) DAY END AS RANGE_LOWER,
 CASE WHEN TIME_PRECISION=9 THEN MONTH_ANCHOR + INTERVAL 1 YEAR - INTERVAL 1 DAY
 WHEN TIME_PRECISION=10 THEN LAST_DAY(MONTH_ANCHOR)
 WHEN TIME_PRECISION=11 AND DAY_VALUE BETWEEN 1 AND DAY(LAST_DAY(MONTH_ANCHOR))
 THEN MONTH_ANCHOR + INTERVAL (DAY_VALUE-1) DAY END AS RANGE_UPPER
 FROM times
)
SELECT ID_STATEMENT,ID_STATEMENT_QUALIFIER,ID_QUALIFIER_PROPERTY,RAW_TIME_VALUE,
 TIME_PRECISION,CALENDAR_MODEL,TIMEZONE_OFFSET,YEAR_VALUE,MONTH_VALUE,DAY_VALUE,
 DATE_START AS SOURCE_DATE_START,DATE_END AS SOURCE_DATE_END,RANGE_LOWER,RANGE_UPPER,
 CASE WHEN RANGE_LOWER IS NULL THEN 'UNSUPPORTED_OR_INVALID'
 WHEN TIME_PRECISION=11 THEN 'EXACT_DAY' ELSE 'PARTIAL_DATE_RANGE' END AS CONVERSION_STATUS,
 CASE WHEN DATE_START IS NOT NULL AND RANGE_LOWER IS NOT NULL
 THEN DATE_START<>RANGE_LOWER ELSE NULL END AS SOURCE_START_DIFFERS
FROM converted ORDER BY ID_STATEMENT,ID_QUALIFIER_PROPERTY,ID_STATEMENT_QUALIFIER;
